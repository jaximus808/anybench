/** What the scoring stage stores in runs.stage_outputs.score. */
export const StoredScoreSchema = z.object({
  version: z.literal(1),
  scorer: z.literal("scoreKit"),
  trials: z.object({
    scored: z.int().nonnegative(),
    warmups: z.int().nonnegative(),
    infra: z.int().nonnegative(),
    /**
     * TDM-248: failed_subject trials our runner stopped and whose workspace our infra lost
     * (core workspaceLostByInfra): "not graded (infra)", left out like infra failures. Absent
     * in scores stored before TDM-248.
     */
    infra_lost: z.int().nonnegative().default(0),
    cancelled: z.int().nonnegative(),
  }),
  /** Measured trials per contender × workload: the n of every comparison. */
  n_per_setup: z.object({ min: z.int().nonnegative(), max: z.int().nonnegative() }),
  /** packages/bench KitScore (plain JSON). */
  kit_score: z.custom<KitScore>(
    (v) =>
      typeof v === "object" &&
      v !== null &&
      Array.isArray((v as { contenders?: unknown }).contenders) &&
      Array.isArray((v as { ranking?: unknown }).ranking),
  ),
});
export type StoredScore = z.infer<typeof StoredScoreSchema>;

function numbersOf(raw: unknown): Record<string, number> {
  const out: Record<string, number> = {};
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return out;
  for (const [k, v] of Object.entries(raw)) {
    if (typeof v === "number" && Number.isFinite(v)) out[k] = v;
  }
  return out;
}

/** trials.gate → gate id → gate.json: the gate record (trial.gate), or a plain map. */
export function gatesOf(raw: unknown): Record<string, GateResult> {
  const record = TrialGateRecordSchema.safeParse(raw);
  if (record.success) return gateResultsOf(record.data);
  const plain = z.record(z.string(), GateResultSchema).safeParse(raw);
  return plain.success ? plain.data : {};
}

/** TDM-248: our infra lost this failed_subject trial's workspace (core workspaceLostByInfra). */
export function lostByInfra(t: StageTrial): boolean {
  return workspaceLostByInfra({
    state: t.state,
    failureClass: t.failure_class ?? null,
    frozen: t.frozen_workspace,
    gateReasons: Object.values(gatesOf(t.gate)).map((g) => g.reason),
    hiddenTestFraction: numbersOf(t.metrics)[HIDDEN_TEST_FRACTION_METRIC],
  });
}

/** A settled trial → the scorer's TrialResult, or why it is left out. */
export function trialResultOf(
  t: StageTrial,
  basis: KitCostBasis = { kind: "compute_proxy" },
):
  | { ok: true; result: TrialResult }
  | { ok: false; why: "warmups" | "infra" | "infra_lost" | "cancelled" } {
  if (t.repeat < 0) return { ok: false, why: "warmups" };
  if (t.state === "failed_infra") return { ok: false, why: "infra" };
  if (t.state === "cancelled") return { ok: false, why: "cancelled" };
  // TDM-248: a workspace our runner lost is not the subject's fail: left out, never a 0.
  if (lostByInfra(t)) return { ok: false, why: "infra_lost" };
  const metrics = numbersOf(t.metrics);
  // Plan 17.2 rule 5: cost comes from the provider side, never from a file the agent can write.
  delete metrics.cost_micro_usd;
  // trials.cost_micro_usd is compute + the attempt's Naïve proxy spend (orchestrator/
  // trial-metrics.ts). When the proxy spend could not be read, compute alone is not the cost: leave
  // it out, so the scorer says "metric missing" instead of reporting a number that is too low.
  // Micro-USD stays an integer; the scorer works on numbers (exact below 2^53).
  // TDM-246 (rule 5's exception): under the kit's `compute_byok_tokens` basis (every contender on
  // the Anthropic key with one pinned Claude Code version), cost also counts the scored attempt's
  // metered model tokens (trial-metrics.ts byok_token_cost_micro_usd). A trial without that
  // reading has no cost: computer time alone would rank it as cheap.
  const byok = basis.kind === "compute_byok_tokens" ? metrics.byok_token_cost_micro_usd : 0;
  if (byok === undefined || !Number.isSafeInteger(byok) || byok < 0) {
    // no reading under the token basis: cost missing
  } else if ((t.cost_micro_usd > 0n || byok > 0) && metrics.proxy_cost_missing !== 1) {
    metrics.cost_micro_usd = Number(t.cost_micro_usd) + byok;
  }
  return {
    ok: true,
    result: {
      trialId: t.id,
      contenderId: t.contender,
      workloadId: t.workload_id,
      repeat: t.repeat,
      metrics,
      gates: gatesOf(t.gate),
      // TDM-232: a subject failure is a failed trial for every gate (graded on its frozen
      // workspace or not); its graded hidden-test fraction still counts as its partial work.
      ...(t.state === "failed_subject" ? { failedSubject: true as const } : {}),
    },
  };
}

/** PipelinePort.score: scoreKit over the run's settled, measured trials. */
export function kitScore(): PipelinePort["score"] {
  return async (_ctx, input) => stageOk(storedScoreOf(input.kit, input.trials));
}

/** scoreKit over the run's settled, measured trials, as runs.stage_outputs.score stores it. */
export function storedScoreOf(kit: KitSpec, trials: readonly StageTrial[]): StoredScore {
  const excluded = { warmups: 0, infra: 0, infra_lost: 0, cancelled: 0 };
  const results: TrialResult[] = [];
  const basis = kitCostBasis(kit);
  for (const t of trials) {
    const r = trialResultOf(t, basis);
    if (r.ok) results.push(r.result);
    else excluded[r.why]++;
  }
  const n = new Map<string, number>();
  for (const r of results) {
    const key = `${r.contenderId}\u0000${r.workloadId}`;
    n.set(key, (n.get(key) ?? 0) + 1);
  }
  const counts = [...n.values()];
  const order = kit.contenders.map((c) => c.id);
  const seen = [...new Set(results.map((r) => r.contenderId))];
  const contenders = [
    ...order.filter((c) => seen.includes(c)),
    ...seen.filter((c) => !order.includes(c)),
  ];
  return {
    version: 1,
    scorer: "scoreKit",
    trials: { scored: results.length, ...excluded },
    n_per_setup: {
      min: counts.length ? Math.min(...counts) : 0,
      max: counts.length ? Math.max(...counts) : 0,
    },
    kit_score: scoreKit(kit, results, { contenders }),
  };
}

