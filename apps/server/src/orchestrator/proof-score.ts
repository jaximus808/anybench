/** One difference sync-shared.mjs found between the league's copies and their sources. */
type SharedProblem = { kind: string; path: string };

/**
 * The league's shared arena against its sources, by the kit's own script
 * (kits/harness-league/scripts/sync-shared.mjs, the one `--check` and the kit test run). Null when
 * every copy is byte-identical; otherwise the differences, or why the check could not run.
 */
export async function sharedArenaProblems(kitDir: string): Promise<string[] | null> {
  const script = path.join(kitDir, "scripts", "sync-shared.mjs");
  let problems: SharedProblem[];
  try {
    const mod = (await import(pathToFileURL(script).href)) as {
      diffShared?: () => SharedProblem[];
    };
    if (typeof mod.diffShared !== "function") return [`${script} exports no diffShared`];
    problems = mod.diffShared();
  } catch (err) {
    return [`could not run ${script}: ${err instanceof Error ? err.message : String(err)}`];
  }
  return problems.length === 0 ? null : problems.map((p) => `${p.kind}: ${p.path}`);
}

/** The checks the offline run verified (oracle passes, every do-less fails). */
const OFFLINE_VERIFIED = ["oracle_passes", "do_less_fails"] as const;

export function curatedProofLabel(commit: string): string {
  return `proof: curated (verified offline at ${commit.slice(0, 7)})`;
}

/** The cuts of a curated kit that its offline proof covers (they only drop setups, tasks, repeats). */
function curatedCuts(id: CuratedKitId, spec: KitSpec) {
  if (id === CURATED_HARNESS_LEAGUE_KIT) return leagueCuts(spec);
  return id === CURATED_LONG_HORIZON_KIT
    ? [longHorizonSmokeProfile(spec)]
    : [smokeProfile(spec), headToHeadProfile(spec), nullPilotProfile(spec)];
}

/** PipelinePort.prove: a curated kit's signed-off offline proof; any other kit holds. */
export function curatedProof(opts: { kitsDir?: string } = {}): PipelinePort["prove"] {
  const kitsDir = defaultKitsDir(opts.kitsDir);
  return async (ctx, input) => {
    const hold = async (reason: string) => {
      await say(ctx, "proof", reason);
      return stageHold<CuratedProof>(reason);
    };
    // Only a kit that was proven offline (or one of its cuts: smoke, head-to-head, null pilot):
    // an edited kit is a different kit. The cuts drop setups, tasks or repeats (the null pilot
    // also copies setup A and points the driver-replacing proof overlays at it); every task, gate
    // and check they keep is proven.
    const want = kitSpecHash(input.kit);
    let id: CuratedKitId | null = null;
    for (const candidate of CURATED_KIT_IDS) {
      let curated: KitSpec;
      try {
        curated = (await loadKit(path.join(kitsDir, candidate))).spec;
      } catch (err) {
        if (!(err instanceof KitLoadError)) throw err;
        continue;
      }
      const hashes = new Set([
        kitSpecHash(curated),
        ...curatedCuts(candidate, curated).flatMap((c) => (c.ok ? [kitSpecHash(c.spec)] : [])),
      ]);
      if (hashes.has(want)) {
        id = candidate;
        break;
      }
    }
    if (id === null) return hold(PROOF_SUITE_UNAVAILABLE);
    const kitDir = path.join(kitsDir, id);

    const signoff = curatedProofSignoff(id);
    const md = await readFile(path.join(kitDir, "PROOF.md"));
    const sha256 = createHash("sha256").update(md).digest("hex");
    if (sha256 !== signoff.sha256) {
      return hold(
        `the curated proof record changed since its sign-off at ${signoff.commit.slice(0, 7)} (sha256 ${sha256.slice(0, 12)}); ${PROOF_SUITE_UNAVAILABLE}`,
      );
    }
    if (signoff.shared_with) {
      const problems = await sharedArenaProblems(kitDir);
      if (problems) {
        return hold(
          `the ${id} kit's arena is no longer a byte-identical copy of ${signoff.shared_with} (${problems.length} difference(s): ${problems.slice(0, 3).join("; ")}); run node kits/${id}/scripts/sync-shared.mjs; ${PROOF_SUITE_UNAVAILABLE}`,
        );
      }
    }
    const text = md.toString("utf8");
    const totals = /^Totals: oracle (.+?); do-nothing (.+?)\.?$/m.exec(text);
    if (!/^Overall: RESULT: PASS$/m.test(text) || !totals) {
      return hold(`the curated proof record does not say PASS; ${PROOF_SUITE_UNAVAILABLE}`);
    }
    const label = curatedProofLabel(signoff.commit);
    const at = `${signoff.source}@${signoff.commit.slice(0, 7)}`;
    const verified: Record<(typeof OFFLINE_VERIFIED)[number], string> = {
      oracle_passes: `oracle ${totals[1]!}`,
      do_less_fails: `do-nothing ${totals[2]!}`,
    };
    const checks: ProofCheckResult[] = PROOF_CHECKS.map((check) =>
      check in verified
        ? {
            check,
            pass: true,
            reason: `${label}: ${verified[check as keyof typeof verified]}`,
            evidence: [at],
          }
        : {
            check,
            pass: false,
            reason: `not run: ${PROOF_SUITE_UNAVAILABLE} ([4.12]); the curated kit is accepted on its offline sign-off`,
            evidence: [],
          },
    );
    const proof: CuratedProof = {
      basis: "curated",
      label,
      source: signoff.source,
      commit: signoff.commit,
      sha256,
      verified: [...OFFLINE_VERIFIED],
      checks,
    };
    await say(
      ctx,
      "proof",
      `${label}: ${verified.oracle_passes}; ${verified.do_less_fails}${signoff.shared_with ? ` (${signoff.shared_with}'s proof: the arena is a byte-identical copy, checked now)` : ""}`,
    );
    return stageOk(proof);
  };
}

/**
 * May this kit leave proof (and pass Go)? All six checks passed, or the proof stage accepted a
 * curated sign-off for exactly this kit row and the checks it verified still pass.
 *
 * `intake` is the run's stored runs.intake. A run from an uploaded kit (TDM-218) is accepted only
 * on all six checks: a curated sign-off (stage_outputs.proof_basis) never applies to it, even if
 * one is somehow stored for its kit row. The uploaded kit is never trusted as is.
 */
export function proofAccepted(
  kit: { id: string; proof: unknown },
  stageOutputs: unknown,
  intake: unknown,
): boolean {
  if (isProven(kit.proof)) return true;
  if (isUploadedKitRun(intake)) return false;
  const outputs = RunStageOutputsShape.safeParse(stageOutputs ?? {});
  const basis = outputs.success ? outputs.data.proof_basis : undefined;
  if (!basis || basis.kit_id !== kit.id) return false;
  const proof = proofOf(kit.proof);
  return basis.verified.every((c) => proof.some((p) => p.check === c && p.pass));
}

