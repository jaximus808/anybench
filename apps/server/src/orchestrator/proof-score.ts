/** Plan 17.2 rule 3: repeats per cell before a difference can be detected. */
export function minRepeats(kind: KitSpec["subject"]["kind"]): number {
  return kind === "software" ? 5 : 10;
}

function fmt(v: number): string {
  if (Number.isInteger(v)) return String(v);
  return Number(v.toPrecision(4)).toString();
}

function nText(min: number, max: number): string {
  return min === max ? `n=${min}` : `n=${min}–${max}`;
}

/**
 * The wording for a score stored before the decision rule existed (no `stats`): never "better".
 * Scores from TDM-175 on carry real verdicts and don't use this.
 */
export function verdictAt(min: number, max: number, kind: KitSpec["subject"]["kind"]): string {
  const need = minRepeats(kind);
  if (min < need) return `no detectable difference at ${nText(min, max)}`;
  return `no verdict at ${nText(min, max)}: significance tests (plan 17.2 rule 2) are not run yet`;
}

function reqLines(kit: KitSpec, c: ContenderScore, reqId: string): string {
  const r = c.requirements.find((x) => x.requirementId === reqId);
  const req = kit.requirements.find((x) => x.id === reqId);
  if (!r) return `${c.contenderId}: no score: not in the score`;
  if (!r.scored) return `${c.contenderId}: ${r.reason}`;
  const unit = req?.type === "measured" && req.unit ? ` ${req.unit}` : "";
  const cells = r.byWorkload.map((cell) => {
    const money = req?.type === "measured" && req.unit === "micro-USD";
    const value =
      cell.status !== "measured" || cell.value === null
        ? "unsolved"
        : money && Number.isSafeInteger(cell.value)
          ? formatUsd(BigInt(cell.value))
          : `${fmt(cell.value)}${unit}`;
    return `${cell.workloadId} ${value} (n=${cell.n}, solved ${cell.solved}/${cell.trials})`;
  });
  return `${c.contenderId}: ${cells.length ? cells.join("; ") : "no workload in common"}`;
}

/** The per-requirement value for the report JSON: only one cell, or the pooled pass rate. */
function requirementValue(r: ContenderScore["requirements"][number]): number | null {
  if (!r.scored) return null;
  if (r.aggregate === "rate") {
    const trials = r.byWorkload.reduce((s, x) => s + x.trials, 0);
    const solved = r.byWorkload.reduce((s, x) => s + x.solved, 0);
    return trials > 0 ? solved / trials : null;
  }
  // TDM-210: the mean hidden-test fraction over every trial, pooled over tasks.
  if (r.aggregate === "all_trials") {
    const xs = r.byWorkload.flatMap((x) => x.samples);
    return xs.length > 0 ? xs.reduce((s, x) => s + x, 0) / xs.length : null;
  }
  // TDM-210: all spend ÷ every hidden test passed, pooled over tasks (integer micro-USD, halves up).
  if (r.aggregate === "per_test_passed") {
    const tests = r.byWorkload.reduce((s, x) => s + (x.testsPassed ?? 0), 0);
    if (tests === 0) return null;
    const spend = r.byWorkload.reduce((s, x) => s + x.samples.reduce((a, v) => a + v, 0), 0);
    return Math.floor((2 * spend + tests) / (2 * tests));
  }
  const only = r.byWorkload.length === 1 ? r.byWorkload[0]! : null;
  return only && only.status === "measured" ? only.value : null;
}

/** The verdict lines for one requirement: one per compared setup (per workload in software kits). */
function verdictLines(ks: KitScore, reqId: string): string[] {
  const out: string[] = [];
  for (const c of ks.contenders) {
    if (c.contenderId === ks.stats.baseline) continue;
    const r = c.requirements.find((x) => x.requirementId === reqId);
    if (!r?.scored) continue;
    if (r.comparison) {
      out.push(`Verdict, ${c.contenderId} vs ${ks.stats.baseline}: ${r.comparison.statement}.`);
      continue;
    }
    const cells = r.byWorkload.filter((cell) => cell.comparison !== null);
    if (cells.length === 0) {
      out.push(`Verdict, ${c.contenderId} vs ${ks.stats.baseline}: none (nothing to compare).`);
      continue;
    }
    out.push(
      `Verdict, ${c.contenderId} vs ${ks.stats.baseline}: ${r.verdict ?? "none"}, per workload:`,
    );
    for (const cell of cells) out.push(`- ${cell.workloadId}: ${cell.comparison!.statement}.`);
  }
  return out;
}

/** E18: one line per compared setup × task, scoped to that task (agent and harness kits). */
function perTaskLines(ks: KitScore, reqId: string, nameOf: (id: string) => string): string[] {
  const out: string[] = [];
  for (const c of ks.contenders) {
    if (c.contenderId === ks.stats.baseline) continue;
    const r = c.requirements.find((x) => x.requirementId === reqId);
    if (!r?.scored) continue;
    for (const cell of r.byWorkload) {
      if (!cell.taskComparison) continue;
      out.push(
        `- ${nameOf(c.contenderId)} on ${cell.workloadId}: ${cell.taskComparison.statement}.`,
      );
    }
  }
  return out;
}

/**
 * The per-task findings as headline sentences, with the setup's display name. Findings of one
 * setup that hold on the same tasks share a sentence: "Tandem ×3 was slower and more expensive on
 * all 3 tasks tested". Scores stored before `where` existed keep their own statements.
 */
export function perTaskHeadlineOf(
  findings: readonly PerTaskFinding[],
  nameOf: (id: string) => string,
): string[] {
  const groups = new Map<string, PerTaskFinding[]>();
  const out: (string | PerTaskFinding[])[] = [];
  for (const f of findings) {
    if (typeof f.where !== "string") {
      out.push(
        f.statement.startsWith(f.contenderId)
          ? `${nameOf(f.contenderId)}${f.statement.slice(f.contenderId.length)}`
          : f.statement,
      );
      continue;
    }
    const key = `${f.contenderId}\u0000${f.where}`;
    const g = groups.get(key);
    if (g) g.push(f);
    else {
      const fresh = [f];
      groups.set(key, fresh);
      out.push(fresh);
    }
  }
  return out.map((x) => {
    if (typeof x === "string") return x;
    const adjectives = x.map((f) => f.adjective);
    const joined =
      adjectives.length === 1
        ? adjectives[0]!
        : `${adjectives.slice(0, -1).join(", ")} and ${adjectives[adjectives.length - 1]!}`;
    return `${nameOf(x[0]!.contenderId)} was ${joined} ${x[0]!.where}`;
  });
}

function verdictIds(c: ContenderScore, verdict: "better" | "worse"): string[] {
  return c.requirements.flatMap((r) =>
    r.scored && r.verdict === verdict ? [r.requirementId] : [],
  );
}

/** bench Comparison → the report's RequirementComparison (null when absent or not representable). */
function reportComparison(cmp: Comparison | null): RequirementComparison | null {
  if (cmp === null) return null;
  const parsed = RequirementComparisonSchema.safeParse({
    baseline_id: cmp.baseline,
    verdict: cmp.verdict,
    test: cmp.test,
    p: cmp.p,
    p_adjusted: cmp.pAdjusted,
    alpha: cmp.alpha,
    family: cmp.family,
    effect: {
      measure: cmp.effect.measure,
      value: cmp.effect.value,
      hodges_lehmann: cmp.effect.hodgesLehmann,
    },
    diff_ci: {
      lo: cmp.ci.lo,
      hi: cmp.ci.hi,
      level: cmp.ci.level,
      requested_level: cmp.ci.requestedLevel,
      attained: cmp.ci.attained,
      unit: cmp.ci.unit,
    },
    n: cmp.n,
    mde: { value: cmp.mde.value, unit: cmp.mde.unit, metric_shift: cmp.mde.metricShift },
    claim: cmp.claim,
    downgraded: cmp.downgraded,
    statement: cmp.statement,
  });
  return parsed.success ? parsed.data : null;
}

export interface SummaryInput {
  kit: KitSpec;
  score: unknown;
  proof: ProofCheckResult[];
  trials: StageTrial[];
  /** The proof record's label (stage_outputs.proof_basis.label), when curated. */
  proofLabel?: string;
  /** Disclosure line about how the setups ran (e.g. the Naïve proxy and simulated approvals). */
  disclosure?: string;
  /**
   * TDM-249: the kit runs its Claude Code setups under the harness league's headless policy. The
   * disclosure is then harnessLeagueDisclosure() of the trials (it replaces `disclosure`): the
   * policy is stated only for the setups whose trial streams carry its start event.
   */
  headlessPolicy?: boolean;
}

/**
 * TDM-232: one line per measured failed_subject trial, e.g. "- A · Claude Code solo, project-tracker
 * #2: stopped at the token cap; graded on its frozen workspace (87 of 120 hidden tests)".
 */
export function subjectFailureLines(
  trials: readonly StageTrial[],
  nameOf: (contender: string) => string,
): string[] {
  return trials
    .filter((t) => t.repeat >= 0 && t.state === "failed_subject" && !lostByInfra(t))
    .map((t) => {
      const m = numbersOf(t.metrics);
      const note = subjectFailureNote({
        failureClass: t.failure_class ?? null,
        frozen: t.frozen_workspace,
        hiddenTestFraction: m[HIDDEN_TEST_FRACTION_METRIC],
        hiddenTestsPassed: m[HIDDEN_TESTS_PASSED_METRIC],
        hiddenTestsTotal: m[HIDDEN_TESTS_TOTAL_METRIC],
      });
      return `- ${nameOf(t.contender)}, ${t.workload_id} #${t.repeat + 1}: ${note}`;
    });
}

/**
 * TDM-248: one line per trial whose workspace our infra lost, e.g. "- B · Claude Code + subagents,
 * project-tracker-xl #1: stopped at the token cap; not graded (infra): our runner stopped it ...".
 */
export function infraLostLines(
  trials: readonly StageTrial[],
  nameOf: (contender: string) => string,
): string[] {
  return trials
    .filter((t) => t.repeat >= 0 && lostByInfra(t))
    .map(
      (t) =>
        `- ${nameOf(t.contender)}, ${t.workload_id} #${t.repeat + 1}: ${subjectFailureNote({
          failureClass: t.failure_class ?? null,
          frozen: t.frozen_workspace,
          gateReasons: Object.values(gatesOf(t.gate)).map((g) => g.reason),
          hiddenTestFraction: numbersOf(t.metrics)[HIDDEN_TEST_FRACTION_METRIC],
        })}`,
    );
}

/** The deterministic report: per-requirement values with n, honest wording, no composite. */
export type SummaryAnalysis = {
  md: string;
  /** The report without run_id, kit_id and comped (the orchestrator sets those). */
  report: Omit<Analysis["report"], "run_id" | "kit_id" | "comped">;
};

export function buildSummary(
  input: SummaryInput,
): { ok: true; analysis: SummaryAnalysis } | { ok: false; reason: string } {
  const parsed = StoredScoreSchema.safeParse(input.score);
  if (!parsed.success) return { ok: false, reason: "the stored score is not a scoreKit result" };
  const score = parsed.data;
  const { kit } = input;
  const ks = score.kit_score;
  const kind = kit.subject.kind;
  const stats = ks.stats as KitScore["stats"] | undefined;
  const decided = stats !== undefined && stats.baseline !== null;
  const head = verdictAt(score.n_per_setup.min, score.n_per_setup.max, kind);
  const nameOf = (id: string) => kit.contenders.find((k) => k.id === id)?.name ?? id;
  // E18: per-task results (agent and harness kits), scoped to the tasks tested.
  const perTask = decided ? (stats.perTask ?? null) : null;
  const perTaskHeadline = perTask ? perTaskHeadlineOf(perTask.headline, nameOf) : [];
  const need = minRepeats(kind);
  const contenderIds = ks.contenders.map((c) => c.contenderId);

  const lines: string[] = [`# ${kit.subject.name}: results`, ""];
  const proofLine =
    input.proofLabel ??
    (isProven(input.proof) ? "proof: all six checks passed" : "proof: not all six checks passed");
  lines.push(proofLine);
  const disclosure = input.headlessPolicy
    ? harnessLeagueDisclosure(kit, input.trials, nameOf)
    : input.disclosure;
  if (disclosure) lines.push(disclosure);
  // TDM-246: say when the cost rows include model tokens (rule 5's exception).
  const costBasis = costBasisDisclosure(kitCostBasis(input.kit));
  if (costBasis) lines.push(costBasis);
  const autoAnswered = autoAnswerLine(input.trials, nameOf);
  if (autoAnswered) lines.push(autoAnswered);
  lines.push("");
  const headline =
    decided && stats.headline.length > 0
      ? stats.headline
          .map((h) => `${h.contenderId} vs ${stats.baseline}: ${h.statement}`)
          .join("; ")
      : null;
  const generalSentence = headline
    ? `Result on ${stats!.primary} (the primary requirement): ${headline}. (${contenderIds.length} setups; ${score.trials.scored} measured trials; Holm-corrected across ${stats!.family} comparisons.) No setup is ranked by a composite score.`
    : `Result: ${head} per setup (${contenderIds.length} setups; ${score.trials.scored} measured trials; the plan needs at least ${need} repeats per setup). No setup is ranked and no composite score is shown.`;
  // The per-task findings lead (every task agreeing, or some with the rest named as no detectable
  // difference); the scope line is always there.
  const sentence = perTask
    ? [
        perTaskHeadline.length ? `On the tasks tested: ${perTaskHeadline.join("; ")}.` : null,
        generalSentence,
        perTask.scope,
      ]
        .filter(Boolean)
        .join(" ")
    : generalSentence;
  lines.push(sentence, "");
  lines.push(
    `Left out of scoring: ${score.trials.warmups} warm-ups, ${score.trials.infra} infra failures (ours), ${score.trials.infra_lost ? `${score.trials.infra_lost} not graded (infra: our runner lost the workspace), ` : ""}${score.trials.cancelled} cancelled.`,
    "",
  );
  // TDM-248: each trial whose workspace our infra lost, named, so nobody reads it as a 0.
  const lost = infraLostLines(input.trials, nameOf);
  if (lost.length) {
    lines.push(
      `Not graded (infra) (${lost.length}; left out of every requirement, never counted as 0, to run again):`,
      ...lost,
      "",
    );
  }
  // TDM-232: what happened to each trial that failed on the subject's side (scored as a fail).
  const stopped = subjectFailureLines(input.trials, nameOf);
  if (stopped.length) {
    lines.push(
      `Stopped early (${stopped.length}, scored as failed trials; a frozen workspace's hidden-test share counts as partial work):`,
      ...stopped,
      "",
    );
  }
  for (const req of kit.requirements) {
    const desc =
      req.type === "measured"
        ? `${req.metric}${req.unit ? `, ${req.unit}` : ""}, ${req.better} is better, gate ${req.gate_id ?? "none"}`
        : `reviewed, scale ${req.scale.min}–${req.scale.max}${req.gate_id ? `, gate ${req.gate_id}` : ""}`;
    lines.push(`## ${req.id}: ${req.title}`, "", `(${desc})`, "");
    for (const c of ks.contenders) lines.push(`- ${reqLines(kit, c, req.id)}`);
    const ns = ks.contenders.flatMap((c) => {
      const r = c.requirements.find((x) => x.requirementId === req.id);
      return r?.scored ? r.byWorkload.map((cell) => cell.trials) : [];
    });
    lines.push("");
    if (decided) lines.push(...verdictLines(ks, req.id), "");
    const taskLines = perTask ? perTaskLines(ks, req.id, nameOf) : [];
    if (taskLines.length)
      lines.push(
        `Per task (each task's repeats as the unit; Holm across ${perTask!.family} task × requirement tests; ${perTask!.scope}):`,
        ...taskLines,
        "",
      );
    else
      lines.push(
        ns.length
          ? `Verdict: ${verdictAt(Math.min(...ns), Math.max(...ns), kind)}.`
          : "Verdict: none (no scored values).",
        "",
      );
  }
  lines.push(
    "## Proof",
    "",
    ...input.proof.map((p) => `- ${p.check}: ${p.pass ? "pass" : "not passed"}: ${p.reason}`),
    "",
  );

  // The report JSON: per-requirement values (one cell or the pooled pass rate), never a composite.
  const byContender = new Map(input.trials.map((t) => [t.contender, t.contender_id]));
  const contenders: ContenderResult[] = ks.contenders.flatMap((c) => {
    const id = byContender.get(c.contenderId);
    const spec = kit.contenders.find((k) => k.id === c.contenderId);
    if (!id) return [];
    return [
      {
        contender_id: id as ContenderResult["contender_id"],
        name: spec?.name ?? c.contenderId,
        role: spec?.role ?? "baseline",
        score: null,
        ci95: null,
        delta_vs_baseline: null,
        requirements: kit.requirements.map((req) => {
          const r = c.requirements.find((x) => x.requirementId === req.id)!;
          const tally = req.gate_id ? c.gates[req.gate_id] : undefined;
          const rate = tally && tally.total > 0 ? tally.passed / tally.total : null;
          const raw = r ? requirementValue(r) : null;
          // No number without a correctness gate: a measured value needs a passing gated trial.
          // TDM-210: except correctness itself (the mean hidden-test fraction over every trial)
          // and the price per hidden test the gate verified, which stand on the gate's own counts.
          const ownCorrectness =
            r?.scored === true &&
            (r.aggregate === "all_trials" || r.aggregate === "per_test_passed");
          const value =
            req.type === "measured" && !ownCorrectness && !(rate !== null && rate > 0) ? null : raw;
          return {
            requirement_id: req.id,
            type: req.type,
            title: req.title,
            value,
            unit:
              req.type === "measured"
                ? (req.unit ?? (r?.scored && r.aggregate === "all_trials" ? "ratio" : null))
                : null,
            ci95: null,
            gate_id: req.gate_id ?? null,
            gate_pass_rate: req.type === "measured" ? rate : null,
            score: null,
            ...(r?.scored ? { n: r.n, survivorship: r.survivorship, aggregate: r.aggregate } : {}),
            ...(decided && r?.scored ? { comparison: reportComparison(r.comparison) } : {}),
            ...(perTask && r?.scored && c.contenderId !== ks.stats.baseline
              ? {
                  by_task: r.byWorkload.flatMap((cell) => {
                    const cmp = reportComparison(cell.taskComparison ?? null);
                    return cmp ? [{ workload_id: cell.workloadId, comparison: cmp }] : [];
                  }),
                }
              : {}),
          };
        }),
        // From the verdicts only: a requirement is a win or a loss when the decision rule says so.
        wins: verdictIds(c, "better"),
        losses: verdictIds(c, "worse"),
      },
    ];
  });
  const failures = Object.fromEntries(FAILURE_CLASSES.map((f) => [f, 0])) as Record<
    (typeof FAILURE_CLASSES)[number],
    number
  >;
  for (const t of input.trials) {
    if (t.repeat < 0) continue;
    if (t.state === "failed_subject") {
      if (lostByInfra(t)) failures.infra++;
      else failures.subject++;
    } else if (t.state === "failed_infra") failures.infra++;
    else if (t.state === "done") {
      const gates = Object.values(gatesOf(t.gate));
      if (gates.some((g) => g.applicable !== false && !g.pass)) failures.gate++;
    }
  }
  const answer = [sentence, proofLine, disclosure].filter(Boolean).join(" ");
  return {
    ok: true,
    analysis: {
      md: lines.join("\n"),
      report: {
        answer,
        contenders,
        where_it_breaks: [],
        bottlenecks: [],
        proof: input.proof,
        failures,
        ...(perTask
          ? {
              per_task: {
                tasks: perTask.tasks,
                family: perTask.family,
                alpha: perTask.alpha,
                scope: perTask.scope,
                headline: perTaskHeadline,
              },
            }
          : {}),
        postmortem: null,
        generated_at: new Date().toISOString(),
      },
    },
  };
}

/** The curated Tandem kit's setups: every contender on the Naïve model proxy (TDM-27/TDM-184). */
export const TANDEM_DISCLOSURE =
  "tokens: naive-proxy, effort: naive-min, thinking: off; simulated approvals";

/** The long-horizon kit's setups: our own Anthropic key, Claude Code's defaults (TDM-212/233). */
export const LONG_HORIZON_DISCLOSURE = "tokens: anthropic-key, effort: default, thinking: on";

/**
 * TDM-228: the harness league's headless policy (kits/harness-league/adapters/headless-policy/
 * policy.mjs; a test checks these against it). A Claude Code session whose last message waits on
 * the user is resumed with this reply, the same for every Claude Code setup.
 */
export const HEADLESS_POLICY_ID = "headless-v1";
export const HEADLESS_POLICY_REPLY =
  "Yes, approved. Proceed with your recommended option and complete the task.";
export const HEADLESS_POLICY_MAX = 8;
/** The metric bench's stream-json collector writes per trial when the policy ran. */
export const QUESTIONS_AUTO_ANSWERED_METRIC = "questions_auto_answered";

const HEADLESS_POLICY_TERMS = `a session that stops to ask is resumed with "${HEADLESS_POLICY_REPLY}" (at most ${HEADLESS_POLICY_MAX} times per trial, counted as ${QUESTIONS_AUTO_ANSWERED_METRIC})`;
const TANDEM_APPROVALS = "Tandem's approvals automatic";

/**
 * The harness league's setups (kits/harness-league): E18's disclosure plus the headless policy.
 * The plan's wording (the run's kit line); a report prints it only when the policy ran in every
 * trial of every Claude Code setup (harnessLeagueDisclosure).
 */
export const HARNESS_LEAGUE_DISCLOSURE = `${LONG_HORIZON_DISCLOSURE}; headless policy ${HEADLESS_POLICY_ID} for every Claude Code setup: ${HEADLESS_POLICY_TERMS}; ${TANDEM_APPROVALS}`;

/** The league drivers that run Claude Code under the headless policy (A, B; G, S via tool-home). */
export const HEADLESS_POLICY_DRIVERS: readonly string[] = [
  "adapters/headless-policy/driver.sh",
  "adapters/tool-home/driver.sh",
];

/** The kit's contenders whose driver applies the headless policy, in kit order. */
export function headlessPolicySetups(kit: KitSpec): string[] {
  return kit.contenders
    .filter(
      (c) => c.driver.script !== undefined && HEADLESS_POLICY_DRIVERS.includes(c.driver.script),
    )
    .map((c) => c.id);
}

/**
 * TDM-249: did the policy run in this trial? The stream-json collector writes
 * `questions_auto_answered` (0 when it never fired) only when the stream carries the policy's
 * start event (`system/anybench_headless_policy`), so its presence is the answer.
 */
export function headlessPolicyRan(t: StageTrial): boolean {
  return numbersOf(t.metrics)[QUESTIONS_AUTO_ANSWERED_METRIC] !== undefined;
}

/**
 * TDM-249: the league's disclosure from what the trials' streams show, not from the plan. Over
 * the measured trials that ran the agent (done or failed_subject) of each policy setup: the
 * policy is stated for the setups where it ran (with "in only k of n trials" when not in all of
 * them), and the setups where no trial's stream has the start event are named as "did not run".
 * When it ran in every such trial of every policy setup, this is HARNESS_LEAGUE_DISCLOSURE.
 */
export function harnessLeagueDisclosure(
  kit: KitSpec,
  trials: readonly StageTrial[],
  nameOf: (contender: string) => string,
): string {
  const applied: string[] = [];
  const partial: string[] = [];
  const didNot: string[] = [];
  for (const id of headlessPolicySetups(kit)) {
    const ran = trials.filter(
      (t) =>
        t.contender === id && t.repeat >= 0 && (t.state === "done" || t.state === "failed_subject"),
    );
    if (ran.length === 0) continue; // nothing to tell from
    const k = ran.filter(headlessPolicyRan).length;
    if (k === 0) didNot.push(nameOf(id));
    else {
      applied.push(nameOf(id));
      if (k < ran.length) partial.push(`${k} of ${ran.length} trials of ${nameOf(id)}`);
    }
  }
  if (didNot.length === 0 && partial.length === 0 && applied.length > 0) {
    return HARNESS_LEAGUE_DISCLOSURE;
  }
  const clauses = [LONG_HORIZON_DISCLOSURE];
  if (applied.length > 0) {
    clauses.push(
      `headless policy ${HEADLESS_POLICY_ID} for ${applied.join(", ")}: ${HEADLESS_POLICY_TERMS}${
        partial.length > 0
          ? `, but it ran in only ${partial.join(", ")} (the other trials' streams have no policy start event)`
          : ""
      }`,
    );
  }
  if (didNot.length > 0) {
    clauses.push(
      `headless policy ${HEADLESS_POLICY_ID} did not run for ${didNot.join(", ")} (no trial's stream has the policy start event)`,
    );
  }
  clauses.push(TANDEM_APPROVALS);
  return clauses.join("; ");
}

/**
 * TDM-228: "questions auto-answered (headless policy): A · Claude Code solo 0 in 5 trials; ..."
 * from the measured trials' `questions_auto_answered`, or null when no trial carries it.
 */
export function autoAnswerLine(
  trials: readonly StageTrial[],
  nameOf: (contender: string) => string,
): string | null {
  const per = new Map<string, { n: number; trials: number }>();
  for (const t of trials) {
    if (t.repeat < 0) continue;
    const v = numbersOf(t.metrics)[QUESTIONS_AUTO_ANSWERED_METRIC];
    if (v === undefined) continue;
    const p = per.get(t.contender) ?? { n: 0, trials: 0 };
    p.n += v;
    p.trials++;
    per.set(t.contender, p);
  }
  if (per.size === 0) return null;
  const parts = [...per].map(
    ([c, p]) => `${nameOf(c)} ${p.n} in ${p.trials} trial${p.trials === 1 ? "" : "s"}`,
  );
  return `questions auto-answered (headless policy): ${parts.join("; ")}`;
}

/**
 * AgentStagePort.analyze without an LLM ([6.8] analyst not built): the summary from the score.
 * The orchestrator sets run_id, kit_id and comped.
 */
export function summaryAnalyst(
  opts: { disclosure?: string; headlessPolicy?: boolean } = {},
): AgentStagePort["analyze"] {
  return async (ctx, input) => {
    const basis = input.proof_basis ?? null;
    const built = buildSummary({
      kit: input.kit,
      score: input.score,
      proof: input.proof,
      trials: input.trials,
      ...(basis && basis.kit_id === input.kit_id ? { proofLabel: basis.label } : {}),
      ...(opts.disclosure ? { disclosure: opts.disclosure } : {}),
      ...(opts.headlessPolicy ? { headlessPolicy: true } : {}),
    });
    if (!built.ok) return stageHold(built.reason);
    await say(ctx, "analyst", `summary (no LLM): ${built.analysis.report.answer}`);
    return stageOk(built.analysis);
  };
}
