// TDM-60 [6.6]: the deterministic materializer for a `driver.type: cli` kit draft.
//
//   resolveCliPins(draft, deps)          every contender's install, pinned by code (pins.ts)
//   materializeCliKit({draft, pins, dir}) the kit folder, written from scratch:
//       anybench.yaml                     KitSpec v2: gates[].capture {from: oracle}, the oracle =
//                                         the pinned subject, every baseline an independent check
//       adapters/<id>/install.sh          the pinned release asset per arch, sha256-checked
//       adapters/<id>/healthcheck.sh      the exact pinned version
//       adapters/<id>/driver.sh           renderCliDriverScript
//       gates/<gate>/check.sh             renderCliGateScript
//       proof/do_less/truncate/driver.sh  renderCliDoLessDriverScript (kind: cheat)
//       proof/do_less/<partial>/          the draft's result-dropping flag (kind: partial-oracle)
//       proof/regression/                 a deterministic planted delay (PLANTED_DELAY_S)
//       workloads/<id>/input/…            the draft's files (+ seeded generated text, replication)
//       design/draft.json, design/pins.json  what the kit was made from (repair input, audit)
//   No reference/ is written: the proof stage captures it from the oracle on the real image.
