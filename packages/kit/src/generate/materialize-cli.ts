export const GENERATED_MARKER = "Generated by @anybench/kit materializeCliKit (TDM-60)";
/** The planted regression's delay before every subject run (deterministic, output unchanged). */
export const PLANTED_DELAY_S = "0.3";
export const PARTIAL_ENV = "AB_PARTIAL";
export const TRUNCATE_DO_LESS_ID = "truncated-output";
export const CLI_WALL_CLOCK_CAP_S = 300;

export class MaterializeError extends Error {
  override readonly name = "MaterializeError";
  /** A network or rate-limit failure while pinning: retry, do not blame the draft. */
  readonly transient: boolean;
  constructor(message: string, opts: { transient?: boolean } = {}) {
    super(message);
    this.transient = opts.transient ?? false;
  }
}

/** Resolve every contender's pin (in parallel; a failure names the contender). */
export async function resolveCliPins(
  draft: CliKitDraft,
  deps: PinDeps = {},
): Promise<Record<string, CliPin>> {
  const entries = await Promise.all(
    draft.contenders.map(async (c): Promise<[string, CliPin]> => {
      try {
        const pin =
          c.install.route === "github_release"
            ? await resolveGithubReleasePin({ repo: c.install.repo, tag: c.install.tag }, deps)
            : await resolveGnuPin(c.install.package, deps);
        return [c.id, pin];
      } catch (err) {
        throw new MaterializeError(
          `contender '${c.id}': ${err instanceof Error ? err.message : String(err)}`,
          { transient: err instanceof PinError && err.transient },
        );
      }
    }),
  );
  return Object.fromEntries(entries);
}

// ---------- deterministic text ----------

const WORDS = (
  "alpha beta gamma delta epsilon zeta theta kappa lambda sigma omega river stone cloud ember " +
  "forest meadow harbor signal vector buffer kernel socket thread module packet cursor ledger " +
  "orbit prism quartz rapid silent tundra umber velvet willow yonder zephyr anchor beacon cobalt " +
  "dune falcon glacier hollow iris jasper lumen marble nectar opal pepper quill raven saffron " +
  "timber utopia vortex wander xenon yarrow zinc copper silver indigo crimson amber violet"
).split(" ");

function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Seeded pseudo-random lines with needles injected every N lines. Same input → same bytes. */
export function generateText(g: {
  lines: number;
  seed: number;
  words_per_line: number;
  inject: { text: string; every: number }[];
}): string {
  const rnd = mulberry32(g.seed);
  const out: string[] = [];
  for (let i = 1; i <= g.lines; i++) {
    const hit = g.inject.find((x) => i % x.every === 0);
    if (hit) {
      out.push(hit.text);
      continue;
    }
    const words: string[] = [];
    for (let w = 0; w < g.words_per_line; w++) words.push(WORDS[Math.floor(rnd() * WORDS.length)]!);
    out.push(words.join(" "));
  }
  return `${out.join("\n")}\n`;
}

/** The workload's files after generation and replication: input-relative path → bytes. */
export function workloadFiles(w: CliDraftWorkload): Map<string, string> {
  const base = new Map<string, string>();
  for (const f of w.files) base.set(f.path, "content" in f ? f.content : generateText(f.generate));
  if (w.replicate <= 1) return base;
  const out = new Map<string, string>();
  for (let k = 1; k <= w.replicate; k++) {
    const dir = `copy-${String(k).padStart(3, "0")}`;
    for (const [p, c] of base) {
      // Files at the input root are parameters (pattern.txt) and stay single. A tree is copied
      // inside its top directory (`tree/a.c` → `tree/copy-001/a.c`), so commands keep naming `tree`.
      const slash = p.indexOf("/");
      if (slash < 0) out.set(p, c);
      else out.set(`${p.slice(0, slash)}/${dir}/${p.slice(slash + 1)}`, c);
    }
  }
  return out;
}

// ---------- scripts ----------

function subjectCommand(c: CliDraftContender, partialArgs: string): string {
  const body = c.command.replace(EXTRA_ARGS_PLACEHOLDER, '${args[@]+"${args[@]}"}');
  return [
    "args=()",
    `# proof overlays (${GENERATED_MARKER}): ${PARTIAL_ENV} → the partial do-less flag, PLANTED_DELAY_S → the planted regression`,
    `if [ -n "\${${PARTIAL_ENV}:-}" ]; then args+=(${partialArgs}); fi`,
    'if [ -n "${PLANTED_DELAY_S:-}" ]; then sleep "$PLANTED_DELAY_S"; fi',
    body,
  ].join("\n");
}

export function driverTemplateOf(draft: CliKitDraft, c: CliDraftContender): CliDriverTemplateInput {
  return {
    contender_id: c.id,
    command: c.role === "subject" ? subjectCommand(c, draft.do_less_partial.args) : c.command,
    exit_codes: c.exit_codes,
    hyperfine: { runs: draft.hyperfine_runs, warmup: 1 },
  };
}

export function renderGithubInstall(binary: string, pin: GithubReleasePin): string {
  const arm = (pattern: string, a: GithubReleasePin["assets"]["x86_64"]) =>
    [
      `  ${pattern})`,
      `    asset=${shQuote(a.name)}`,
      `    url=${shQuote(a.url)}`,
      `    sha=${a.sha256}`,
      "    ;;",
    ].join("\n");
  return [
    "#!/usr/bin/env bash",
    `# L1 install: runs once at snapshot build. Installs the pinned ${pin.repo} ${pin.tag} release`,
    "# binary for this machine's arch, checked against the sha256 pinned below.",
    `# ${GENERATED_MARKER}: asset URLs and sha256 were resolved by code, not written by a model.`,
    "set -euo pipefail",
    'case "$(uname -m)" in',
    arm("x86_64 | amd64", pin.assets.x86_64),
    arm("aarch64 | arm64", pin.assets.aarch64),
    `  *) echo "install.sh: no ${pin.repo} ${pin.tag} build for $(uname -m)" >&2; exit 1 ;;`,
    "esac",
    'tmp="$(mktemp -d)"',
    "trap 'rm -rf \"$tmp\"' EXIT",
    'curl -fsSL --retry 3 -o "$tmp/$asset" "$url"',
    'echo "$sha  $tmp/$asset" | sha256sum -c - > /dev/null',
    'mkdir -p "$tmp/x"',
    'case "$asset" in',
    '  *.tar.gz | *.tgz) tar -xzf "$tmp/$asset" -C "$tmp/x" ;;',
    '  *.tar.xz | *.txz) tar -xJf "$tmp/$asset" -C "$tmp/x" ;;',
    '  *.tar.bz2) tar -xjf "$tmp/$asset" -C "$tmp/x" ;;',
    '  *.zip) (cd "$tmp/x" && unzip -q "$tmp/$asset") ;;',
    `  *) cp "$tmp/$asset" "$tmp/x/"${shQuote(binary)} ;;`,
    "esac",
    `bin="$(find "$tmp/x" -type f -name ${shQuote(binary)} | head -n 1)"`,
    `[ -n "$bin" ] || { echo "install.sh: no ${binary} in $asset" >&2; exit 1; }`,
    `install -m 0755 "$bin" /usr/local/bin/${shQuote(binary)}`,
    "",
  ].join("\n");
}

export function renderGnuInstall(binary: string, aptPackage: string): string {
  return [
    "#!/usr/bin/env bash",
    `# L1 install: GNU ${aptPackage} from the base image's apt (pinned by version in healthcheck.sh).`,
    `# ${GENERATED_MARKER}.`,
    "set -euo pipefail",
    `if ! command -v ${shQuote(binary)} > /dev/null 2>&1; then`,
    "  apt-get update -qq",
    `  DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends ${shQuote(aptPackage)}`,
    "fi",
    "",
  ].join("\n");
}

export function renderHealthcheck(versionCommand: string, version: string): string {
  return [
    "#!/usr/bin/env bash",
    `# ${GENERATED_MARKER}: the installed version must be exactly the pinned one.`,
    "set -euo pipefail",
    `${versionCommand} 2>&1 | head -n 3 | grep -qF -- ${shQuote(version)}`,
    "",
  ].join("\n");
}

// ---------- the kit ----------

export interface MaterializeCliKitInput {
  draft: CliKitDraft;
  pins: Record<string, CliPin>;
  /** The kit directory (created; an existing one is replaced: it is not referenced yet). */
  dir: string;
  /** schedule.order_seed. Default: from the draft's hash. */
  orderSeed?: number;
  /** Written to design/provenance.json (run id, model, session ids). Never secrets. */
  provenance?: Record<string, unknown>;
}

export interface MaterializedCliKit {
  dir: string;
  /** The KitSpec as written to anybench.yaml (validate it with loadKit). */
  spec: Record<string, unknown>;
  /** Kit-relative paths written. */
  files: string[];
}

function sha256(s: string): string {
  return createHash("sha256").update(s).digest("hex");
}

function versionLabel(c: CliDraftContender, pin: CliPin): string {
  return `${c.name} ${pin.version}`;
}

export function cliKitSpec(
  draft: CliKitDraft,
  pins: Record<string, CliPin>,
  orderSeed: number,
): Record<string, unknown> {
  const subject = draft.contenders.find((c) => c.role === "subject")!;
  const gate = draft.gate;
  const reference = `reference/${gate.id}/`;
  const contenders = draft.contenders.map((c) => {
    const pin = pins[c.id];
    if (!pin) throw new MaterializeError(`contender '${c.id}' has no pin`);
    const source =
      pin.kind === "github_release"
        ? { github: pin.repo, ref: pin.tag }
        : { binary_url: pin.url, sha256: pin.sha256 };
    return {
      id: c.id,
      name: c.name,
      role: c.role,
      source,
      driver: {
        type: "cli",
        verbs: { run: `adapters/${c.id}/driver.sh run {in} {out}` },
        wall_clock_cap_s: CLI_WALL_CLOCK_CAP_S,
      },
      version: versionLabel(c, pin),
      found_by: c.role === "subject" ? "the repo under test" : `kit designer: ${c.why}`,
    };
  });
  return {
    schema_version: 2,
    subject: {
      kind: "software",
      ...draft.subject,
      horizon: { horizon: draft.horizon.horizon, rationale: draft.horizon.rationale },
    },
    contenders,
    workloads: draft.workloads.map((w) => ({
      id: w.id,
      title: w.title,
      ...(w.params ? { params: w.params } : {}),
    })),
    gates: [
      {
        id: gate.id,
        kind: "output-diff",
        reference,
        capture: { from: "oracle" },
        description: `${gate.description} The reference is captured from the pinned ${subject.name} on the real image and confirmed by every baseline.`,
      },
    ],
    requirements: [
      {
        id: "wall",
        type: "measured",
        title: "Wall time",
        metric: "wall_s",
        unit: "s",
        better: "lower",
        gate_id: gate.id,
      },
      {
        id: "rss",
        type: "measured",
        title: "Peak RSS",
        metric: "peak_rss_bytes",
        unit: "bytes",
        better: "lower",
        gate_id: gate.id,
      },
    ],
    proof: {
      oracle: {
        id: `${subject.id}-reference`,
        dir: "proof/oracle/",
        contender: subject.id,
        description: `The pinned ${subject.name} release: its output on the real image is the reference; an independent baseline must agree.`,
      },
      do_less: [
        {
          id: TRUNCATE_DO_LESS_ID,
          dir: "proof/do_less/truncate/",
          contender: subject.id,
          driver_patch: "proof/do_less/truncate/driver.sh",
          kind: "cheat",
          description: "The subject's stdout cut to its first line; must fail the gate.",
        },
        {
          id: draft.do_less_partial.id,
          dir: `proof/do_less/${draft.do_less_partial.id}/`,
          contender: subject.id,
          env: { [PARTIAL_ENV]: "1" },
          kind: "partial-oracle",
          description: draft.do_less_partial.description,
        },
      ],
      regression: {
        id: "planted-delay",
        dir: "proof/regression/",
        contender: subject.id,
        env: { PLANTED_DELAY_S },
        description: `A deterministic planted slowdown (${PLANTED_DELAY_S} s before every run, output unchanged); must score lower on wall time.`,
      },
    },
    scoring: {
      weights: { wall: draft.weights.wall, rss: draft.weights.rss },
      primary: draft.primary,
    },
    repeats: draft.repeats,
    schedule: { order_seed: orderSeed },
    env: {
      profile: "base",
      resources: { vcpu: 2, memory_gb: 4, disk_gb: 20 },
      os_packages: ["hyperfine"],
    },
  };
}

async function put(dir: string, rel: string, content: string, files: string[], mode = 0o644) {
  const abs = path.join(dir, rel);
  await mkdir(path.dirname(abs), { recursive: true });
  await writeFile(abs, content, { mode });
  files.push(rel);
}

/** Write the kit folder. Deterministic: the same draft and pins give the same bytes. */
export async function materializeCliKit(
  input: MaterializeCliKitInput,
): Promise<MaterializedCliKit> {
  const { draft, pins } = input;
  const dir = path.resolve(input.dir);
  const draftJson = JSON.stringify(draft, null, 2);
  const orderSeed = input.orderSeed ?? parseInt(sha256(draftJson).slice(0, 8), 16);

  // Size limits after generation, before anything is written.
  const workloads = new Map<string, Map<string, string>>();
  for (const w of draft.workloads) {
    const files = workloadFiles(w);
    const bytes = [...files.values()].reduce((n, c) => n + Buffer.byteLength(c), 0);
    for (const [p, c] of files) {
      const b = Buffer.byteLength(c);
      if (b > CLI_DRAFT_LIMITS.fileBytes)
        throw new MaterializeError(
          `workload '${w.id}' file ${p} is ${b} bytes (max ${CLI_DRAFT_LIMITS.fileBytes} per file): split it into several files or generate fewer lines`,
        );
    }
    if (files.size > CLI_DRAFT_LIMITS.workloadFiles)
      throw new MaterializeError(
        `workload '${w.id}' has ${files.size} files after replication (max ${CLI_DRAFT_LIMITS.workloadFiles})`,
      );
    if (bytes > CLI_DRAFT_LIMITS.workloadBytes)
      throw new MaterializeError(
        `workload '${w.id}' is ${bytes} bytes (max ${CLI_DRAFT_LIMITS.workloadBytes})`,
      );
    workloads.set(w.id, files);
  }

  const spec = cliKitSpec(draft, pins, orderSeed);
  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });
  const files: string[] = [];
  const subject = draft.contenders.find((c) => c.role === "subject")!;

  await put(
    dir,
    "anybench.yaml",
    [
      `# ${GENERATED_MARKER} from the kit designer's draft (design/draft.json).`,
      "# Scripts are rendered by @anybench/kit; release URLs and sha256 were pinned by code.",
      "# The gate's reference is captured from the oracle (the pinned subject) by the proof stage.",
      stringify(spec, { lineWidth: 100 }),
    ].join("\n"),
    files,
  );

  for (const c of draft.contenders) {
    const pin = pins[c.id]!;
    const install =
      pin.kind === "github_release"
        ? renderGithubInstall(c.binary, pin)
        : renderGnuInstall(c.binary, GNU_BASELINES[pin.package].apt_package);
    await put(dir, `adapters/${c.id}/install.sh`, install, files, 0o755);
    await put(
      dir,
      `adapters/${c.id}/healthcheck.sh`,
      renderHealthcheck(c.version_command, pin.version),
      files,
      0o755,
    );
    await put(
      dir,
      `adapters/${c.id}/driver.sh`,
      renderCliDriverScript(driverTemplateOf(draft, c)),
      files,
      0o755,
    );
  }

  await put(
    dir,
    `gates/${draft.gate.id}/check.sh`,
    renderCliGateScript({
      gate_id: draft.gate.id,
      reference: `reference/${draft.gate.id}/`,
      sort_lines: draft.gate.sort_lines,
      exit_codes: draft.gate.exit_codes,
    }),
    files,
    0o755,
  );

  await put(
    dir,
    `reference/${draft.gate.id}/README.md`,
    `# Reference for gate ${draft.gate.id}\n\nEmpty on purpose: the proof stage captures \`<workload>/stdout.txt\` here from the oracle\n(the pinned ${subject.name}) on the real image. Scoring-only: never staged on a subject computer.\n`,
    files,
  );
  await put(
    dir,
    "proof/oracle/README.md",
    `# Oracle: the pinned ${subject.name}\n\nNo patch, no env: the subject's own pinned release. The proof stage captures\n\`reference/${draft.gate.id}/<workload>/stdout.txt\` from its output on the real image, re-runs it on a\nfresh computer, and requires an independent baseline to pass the same gate.\n`,
    files,
  );
  await put(
    dir,
    "proof/do_less/truncate/driver.sh",
    renderCliDoLessDriverScript(driverTemplateOf(draft, subject), { keep_lines: 1 }),
    files,
    0o755,
  );
  await put(
    dir,
    "proof/do_less/truncate/README.md",
    "# Do-less (cheat): truncated output\n\nThe subject's stdout cut to its first line. Must fail the gate.\n",
    files,
  );
  await put(
    dir,
    `proof/do_less/${draft.do_less_partial.id}/README.md`,
    `# Do-less (partial): ${draft.do_less_partial.id}\n\nSets \`${PARTIAL_ENV}=1\`, which adds \`${draft.do_less_partial.args}\` to the subject's command.\n${draft.do_less_partial.description}\n`,
    files,
  );
  await put(
    dir,
    "proof/regression/README.md",
    `# Planted regression: a fixed delay\n\nSets \`PLANTED_DELAY_S=${PLANTED_DELAY_S}\`: the subject sleeps ${PLANTED_DELAY_S} s before every run, so output is\nunchanged (the gate passes) but wall time must score lower. Deterministic on purpose.\n`,
    files,
  );

  for (const [id, wf] of workloads) {
    for (const [p, c] of [...wf].sort(([a], [b]) => a.localeCompare(b))) {
      await put(dir, `workloads/${id}/input/${p}`, c, files);
    }
  }

  await put(dir, "design/draft.json", `${draftJson}\n`, files);
  await put(dir, "design/pins.json", `${JSON.stringify(pins, null, 2)}\n`, files);
  if (input.provenance)
    await put(
      dir,
      "design/provenance.json",
      `${JSON.stringify(input.provenance, null, 2)}\n`,
      files,
    );

  return { dir, spec, files };
}
