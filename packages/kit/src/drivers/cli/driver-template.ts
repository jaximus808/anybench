// TDM-36 [4.4]: `adapters/<id>/driver.sh` for `driver.type: cli`.
//
// The rendered driver implements the L2 verbs (start | ready | run <in> <out> | stop; a cli
// needs only `run`) and wraps the subject with the cli collectors:
//
//   1. the gated run: once, under GNU `time -v`, stdout/stderr/exit code and `$CLI_FILES_OUT`
//      captured under <out>/cli/. This is the run the output-diff gate checks, and the run the
//      `time` metrics (wall, CPU, peak RSS) describe, so every one of those numbers is vouched
//      for by the gate of the very same execution.
//   2. the timed runs: `hyperfine --export-json` over the same `subject` function, stdout to
//      /dev/null and files to a scratch dir, so they can never change what the gate sees.
//
// The subject is a bash function exported into both tools (`export -f`), so time and hyperfine
// run the identical code path. The do-less variant differs in one line: `subject` pipes the
// command through `head -n K`, i.e. it skips producing most of its output.
import {
  CliDoLessTruncateSchema,
  CliDriverTemplateSchema,
  type CliDoLessTruncateInput,
  type CliDriverTemplate,
  type CliDriverTemplateInput,
} from "./options.js";
import { CLI_OUTPUT_PATHS as P } from "./outputs.js";
import { CLI_SCRIPT_SHEBANG, indent, shQuote } from "./shell.js";

/** Marker in every rendered cli script: tests and the kit designer use it to spot generated files. */
export const CLI_GENERATED_MARKER = "Generated by @anybench/kit";

function subjectLine(doLess: { keep_lines: number } | undefined): string {
  return doLess === undefined
    ? "subject() { subject_cmd; }"
    : `subject() { subject_cmd | head -n ${doLess.keep_lines}; }`;
}

function render(t: CliDriverTemplate, doLess: { keep_lines: number } | undefined): string {
  const useTime = t.collectors.includes("time");
  const useHyperfine = t.collectors.includes("hyperfine");
  const acceptsFailure = t.exit_codes.some((c) => c !== 0);
  const title =
    doLess === undefined
      ? `L2 driver for contender '${t.contender_id}' (driver.type: cli).`
      : `L7 do-less overlay for contender '${t.contender_id}' (driver.type: cli): stdout cut to ${doLess.keep_lines} line(s).`;

  const gated = useTime ? `"$gnu_time" -v -o "$out/${P.time}" bash -c subject` : "bash -c subject";
  const hyperfineArgs = [
    "--shell=bash",
    "--style=basic",
    `--runs ${t.hyperfine.runs}`,
    `--warmup ${t.hyperfine.warmup}`,
    "--output=null",
    ...(acceptsFailure ? ["--ignore-failure"] : []),
    `--export-json "$out/${P.hyperfine}"`,
    '--command-name "$contender"',
  ].join(" ");

  const lines: string[] = [
    CLI_SCRIPT_SHEBANG,
    `# ${title}`,
    `# ${CLI_GENERATED_MARKER} renderCli${doLess === undefined ? "" : "DoLess"}DriverScript (TDM-36): regenerate it, do not edit by hand.`,
    "#",
    "# Verbs: start | ready | stop are no-ops (a cli keeps nothing running) | run <in> <out>.",
    "# run writes under <out>:",
    `#   ${P.stdout.padEnd(16)} stdout of the gated run (the output-diff gate compares it)`,
    `#   ${P.stderr.padEnd(16)} its stderr`,
    `#   ${P.exitCode.padEnd(16)} its exit status`,
    `#   ${(P.filesDir + "/").padEnd(16)} files it wrote under $CLI_FILES_OUT`,
    ...(useTime
      ? [`#   ${P.time.padEnd(16)} GNU time -v report of the gated run (collector: time)`]
      : []),
    ...(useHyperfine
      ? [
          `#   ${P.hyperfine.padEnd(16)} hyperfine --export-json of the timed runs (collector: hyperfine)`,
        ]
      : []),
    "set -euo pipefail",
    "",
    "# The subject, as the kit wrote it. cwd is <in>; output files go under $CLI_FILES_OUT.",
    "subject_cmd() {",
    indent(t.command.replace(/\s+$/, "")),
    "}",
    "# What the contender runs: the gated run and every timed run call this.",
    subjectLine(doLess),
    "export -f subject_cmd subject",
    "",
    `contender=${shQuote(t.contender_id)}`,
    `accepted_exit_codes=' ${t.exit_codes.join(" ")} '`,
    "",
    'die() { echo "driver.sh ($contender): $*" >&2; exit 1; }',
    "",
    "run_subject() {",
    '  local in="${1:?usage: driver.sh run <in> <out>}" out="${2:?usage: driver.sh run <in> <out>}"',
    '  in="$(cd "$in" && pwd)"',
    '  mkdir -p "$out"',
    '  out="$(cd "$out" && pwd)"',
    `  mkdir -p "$out/${P.filesDir}"`,
    ...(useTime
      ? [
          '  local gnu_time="${ANYBENCH_GNU_TIME:-/usr/bin/time}"',
          '  [ -x "$gnu_time" ] || die "GNU time not found at $gnu_time (the base profile installs it; set ANYBENCH_GNU_TIME)"',
        ]
      : []),
    ...(useHyperfine
      ? [
          '  command -v hyperfine > /dev/null || die "hyperfine not on PATH (the base profile installs it)"',
        ]
      : []),
    "",
    "  # 1. The gated run.",
    "  local rc=0",
    `  (cd "$in" && CLI_FILES_OUT="$out/${P.filesDir}" ${gated}) \\`,
    `    > "$out/${P.stdout}" 2> "$out/${P.stderr}" || rc=$?`,
    `  printf '%s\\n' "$rc" > "$out/${P.exitCode}"`,
    '  case "$accepted_exit_codes" in',
    '    *" $rc "*) ;;',
    '    *) die "the subject exited $rc (accepted:$accepted_exit_codes); see the stderr log" ;;',
    "  esac",
    ...(useHyperfine
      ? [
          "",
          "  # 2. The timed runs: stdout discarded, files to a scratch dir, never to the gated outputs.",
          "  local scratch",
          '  scratch="$(mktemp -d)"',
          `  if ! (cd "$in" && CLI_FILES_OUT="$scratch" hyperfine ${hyperfineArgs} subject) \\`,
          `    > "$out/${P.hyperfineLog}" 2>&1; then`,
          '    rm -rf "$scratch"',
          `    die "hyperfine failed; see ${P.hyperfineLog}"`,
          "  fi",
          '  rm -rf "$scratch"',
        ]
      : []),
    "}",
    "",
    'case "${1:-}" in',
    "  start | ready | stop) exit 0 ;;",
    "  run)",
    "    shift",
    '    run_subject "$@"',
    "    ;;",
    "  *)",
    '    echo "usage: driver.sh start | ready | run <in> <out> | stop" >&2',
    "    exit 2",
    "    ;;",
    "esac",
    "",
  ];
  return lines.join("\n");
}

/** Render the honest `adapters/<id>/driver.sh` for a cli contender. */
export function renderCliDriverScript(input: CliDriverTemplateInput): string {
  return render(CliDriverTemplateSchema.parse(input), undefined);
}

/**
 * Render the do-less overlay driver: the same script with the subject's stdout truncated. Put it
 * at `proof/do_less/<id>/driver.sh` and name it as the overlay's `driver_patch`; the overlay
 * replaces the contender's driver.sh with it. It must fail the output-diff gate.
 */
export function renderCliDoLessDriverScript(
  input: CliDriverTemplateInput,
  doLess: CliDoLessTruncateInput = {},
): string {
  return render(CliDriverTemplateSchema.parse(input), CliDoLessTruncateSchema.parse(doLess));
}
