// TDM-36 [4.4]: `gates/<id>/check.sh` for the cli output-diff gate (GateKind `output-diff`).
//
// Runs only on the scoring computer, as its own process, over one trial's frozen outputs:
//   check.sh <frozen-out> <workload-id> <gate.json>
// It never runs contender code (TDM-128 review: hidden checks must not share a process with the
// contender). It only reads files: the gated run's exit code, stdout and declared output files,
// each compared with `<reference>/<workload>/{stdout.txt,files/<path>}`. It writes
// `gate.json {pass, reason, evidence[]}` (core GateResultSchema) and, when something differs, a
// unified diff next to it (`<gate.json minus .json>.diff`).
//
// Exit status: 0 whenever a verdict was written (pass or fail: a failing contender is not a gate
// error); 2 for a usage or kit error (bad workload id, no reference), with no verdict, so the
// trial reads "gate missing" rather than a pass or a fail the kit did not earn.
//
// Frozen outputs are untrusted: a path that is a symlink, not a regular file, or resolves
// outside <frozen-out> fails the gate.
//
// The bash is kept in plain (non-template) strings so `${...}` is bash's, not TypeScript's.
import { normalizeKitPath } from "../../layout.js";
import { CLI_GENERATED_MARKER } from "./driver-template.js";
import { CliGateTemplateSchema, type CliGateTemplateInput } from "./options.js";
import { CLI_OUTPUT_PATHS as P } from "./outputs.js";
import { CLI_SCRIPT_SHEBANG, shQuote } from "./shell.js";

const BODY: readonly string[] = [
  'usage() { echo "check.sh: $*" >&2; exit 2; }',
  '[ "$#" -eq 3 ] || usage "usage: check.sh <frozen-out> <workload-id> <gate.json>"',
  'out="$1" workload="$2" verdict="$3"',
  "",
  "printf '%s' \"$workload\" | grep -Eq '^[a-z0-9][a-z0-9._-]{0,63}$' || usage \"bad workload id: $workload\"",
  '[ -d "$out" ] || usage "frozen outputs not found: $out"',
  'kit_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"',
  'ref="$kit_root/$reference_dir/$workload"',
  '[ -d "$ref" ] || usage "no reference for workload $workload at $reference_dir/$workload"',
  'out_real="$(cd "$out" && pwd -P)"',
  'diff_file="${verdict%.json}.diff"',
  'work="$(mktemp -d)"',
  "trap 'rm -rf \"$work\"' EXIT",
  ': > "$work/diff"',
  "",
  "failures=()",
  "evidence=()",
  "",
  "# JSON string: control characters dropped, backslash and quote escaped.",
  String.raw`json_str() { printf '"%s"' "$(printf '%s' "$1" | tr -d '\000-\037' | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"; }`,
  "",
  "write_verdict() {",
  '  local pass="$1" reason="$2" first=1 e',
  "  {",
  '    printf \'{"pass":%s,"reason":%s,"evidence":[\' "$pass" "$(json_str "$reason")"',
  '    for e in ${evidence[@]+"${evidence[@]}"}; do',
  "      [ \"$first\" -eq 1 ] || printf ','",
  "      first=0",
  '      json_str "$e"',
  "    done",
  String.raw`    printf ']}\n'`,
  '  } > "$verdict.tmp"',
  '  mv "$verdict.tmp" "$verdict"',
  "}",
  "",
  "# A frozen path the gate may read: a regular file, not a symlink, inside <frozen-out>.",
  "safe_file() {",
  '  local rel="$1" p="$out/$1" real',
  '  if [ -L "$p" ]; then',
  '    failures+=("$rel is a symlink")',
  "    return 1",
  "  fi",
  '  if [ ! -e "$p" ]; then',
  '    failures+=("$rel is missing")',
  "    return 1",
  "  fi",
  '  if [ ! -f "$p" ]; then',
  '    failures+=("$rel is not a regular file")',
  "    return 1",
  "  fi",
  '  real="$(cd "$(dirname "$p")" && pwd -P)/$(basename "$p")"',
  '  case "$real" in',
  '    "$out_real"/*) return 0 ;;',
  "  esac",
  '  failures+=("$rel resolves outside the frozen outputs")',
  "  return 1",
  "}",
  "",
  "lines_of() { awk 'END { print NR }' \"$1\"; }",
  "",
  "# compare <frozen-rel> <reference-file> <sort 0|1>",
  "compare() {",
  '  local rel="$1" want="$2" sort="$3" got="$out/$1" a b missing extra detail',
  '  evidence+=("$rel")',
  '  safe_file "$rel" || return 0',
  '  [ -f "$want" ] || usage "reference file missing: ${want#"$kit_root/"}"',
  '  if [ "$sort" -eq 1 ]; then',
  '    a="$work/want.sorted" b="$work/got.sorted"',
  '    sort "$want" > "$a"',
  '    sort "$got" > "$b"',
  "  else",
  '    a="$want" b="$got"',
  "  fi",
  '  cmp -s "$a" "$b" && return 0',
  '  diff -u "$a" "$b" | sed -e "1s|^--- .*|--- reference/$rel|" -e "2s|^+++ .*|+++ $rel|" >> "$work/diff" || true',
  '  sort "$want" > "$work/want.set"',
  '  sort "$got" > "$work/got.set"',
  '  missing="$(comm -23 "$work/want.set" "$work/got.set" | awk \'END { print NR }\')"',
  '  extra="$(comm -13 "$work/want.set" "$work/got.set" | awk \'END { print NR }\')"',
  '  detail="$rel differs from the reference: got $(lines_of "$got") line(s), expected $(lines_of "$want")"',
  '  if [ "$missing" -gt 0 ] && [ "$extra" -eq 0 ]; then',
  '    detail="$detail; $missing expected line(s) missing and none extra (output truncated?)"',
  '  elif [ "$missing" -eq 0 ] && [ "$extra" -eq 0 ]; then',
  '    detail="$detail; the same lines in a different order or with different line endings"',
  "  else",
  '    detail="$detail; $missing expected line(s) missing, $extra unexpected"',
  "  fi",
  '  failures+=("$detail")',
  "}",
  "",
  "# 1. The gated run ended with an accepted exit code.",
  'evidence+=("$exit_code_file")',
  'if safe_file "$exit_code_file"; then',
  String.raw`  rc="$(tr -d ' \n\r' < "$out/$exit_code_file")"`,
  '  case "$rc" in',
  "    '' | *[!0-9]*) failures+=(\"$exit_code_file is not an exit status\") ;;",
  "    *)",
  '      case "$accepted_exit_codes" in',
  '        *" $rc "*) ;;',
  '        *) failures+=("the subject exited $rc (accepted:$accepted_exit_codes)") ;;',
  "      esac",
  "      ;;",
  "  esac",
  "fi",
  "",
  "# 2. stdout equals the reference.",
  'if [ "$compare_stdout" -eq 1 ]; then',
  '  compare "$stdout_file" "$ref/stdout.txt" "$sort_lines"',
  "fi",
  "",
  "# 3. Every declared output file equals the reference, byte for byte.",
  'for f in ${files[@]+"${files[@]}"}; do',
  '  compare "$files_dir/$f" "$ref/files/$f" 0',
  "done",
  "",
  'if [ -s "$work/diff" ]; then',
  '  cp "$work/diff" "$diff_file"',
  "fi",
  'if [ "${#failures[@]}" -eq 0 ]; then',
  '  what="exit code"',
  '  [ "$compare_stdout" -eq 1 ] && what="$what and stdout"',
  '  [ "${#files[@]}" -gt 0 ] && what="$what and ${#files[@]} output file(s)"',
  '  write_verdict true "$gate_id: $what equal the reference for $workload"',
  "else",
  '  reason="$gate_id: $workload failed: ${failures[0]}"',
  "  i=1",
  '  while [ "$i" -lt "${#failures[@]}" ]; do',
  '    reason="$reason; ${failures[$i]}"',
  "    i=$((i + 1))",
  "  done",
  '  write_verdict false "$reason"',
  "fi",
  "",
];

/** Render `gates/<gate_id>/check.sh` for an output-diff gate over cli outputs. */
export function renderCliGateScript(input: CliGateTemplateInput): string {
  const g = CliGateTemplateSchema.parse(input);
  const reference = normalizeKitPath(g.reference ?? `reference/${g.gate_id}`);
  const head = [
    CLI_SCRIPT_SHEBANG,
    `# L5 gate '${g.gate_id}' (kind: output-diff) for driver.type: cli.`,
    `# ${CLI_GENERATED_MARKER} renderCliGateScript (TDM-36): regenerate it, do not edit by hand.`,
    "#",
    "# Usage: check.sh <frozen-out> <workload-id> <gate.json>",
    "# Runs only on the scoring computer, as its own process, over the frozen outputs of one trial.",
    `# It never runs contender code: it reads files and compares them with ${reference}/<workload>/`,
    "# (stdout.txt, files/<path>). A diff of what differs goes next to gate.json (<gate>.diff).",
    "# Exit 0 = a verdict was written (pass or fail). Exit 2 = usage or kit error, no verdict.",
    "set -euo pipefail",
    "export LC_ALL=C",
    "",
    `gate_id=${shQuote(g.gate_id)}`,
    `reference_dir=${shQuote(reference)}`,
    `compare_stdout=${g.stdout ? 1 : 0}`,
    `sort_lines=${g.sort_lines ? 1 : 0}`,
    `accepted_exit_codes=' ${g.exit_codes.join(" ")} '`,
    `files=(${g.files.map(shQuote).join(" ")})`,
    `exit_code_file=${shQuote(P.exitCode)}`,
    `stdout_file=${shQuote(P.stdout)}`,
    `files_dir=${shQuote(P.filesDir)}`,
    "",
  ];
  return [...head, ...BODY].join("\n");
}
