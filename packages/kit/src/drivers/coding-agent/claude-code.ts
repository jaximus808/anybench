// TDM-39 [4.7]: bash building blocks for running headless Claude Code on an eval computer.
//
// Shared by the coding-agent driver (this directory) and the harness driver (TDM-41), which runs
// Claude Code for Tandem's planner and workers the same way. Each block is a bash fragment the
// rendered driver.sh embeds verbatim; they need bash 3.2+ (the tests run them on macOS) and use
// only POSIX tools plus `node` (Claude Code needs it anyway).
//
// The rules they enforce (plan.md P1 secrets, 17.2 rules 4 and 5):
// - The agent never runs as root: it runs as a separate non-root user (`eval` on the agent-cc
//   profile), switched to with runuser (root, docker-local) or `sudo -n` (Naïve's user), in a
//   clean environment (`env -i`). Its workspace, task and config are copies under its own HOME,
//   so it never needs (or gets) access to the runner's HOME, where ~/.anybench/env and the
//   per-trial ingest token live.
// - Model tokens come from one source per run (rule 4): the Naïve proxy (default; the worker's
//   per-trial proxy env file) or a direct Anthropic key (BYOK). Either way the credentials reach
//   it only as 0600 files under its HOME, written through a pipe (never argv), read into Claude
//   Code's env by the launcher, and deleted before Claude Code starts.
// - What the driver keeps (stream-json, stderr) has every secret value replaced by [REDACTED],
//   by an awk filter that gets the values through its environment, never argv.
// - The Claude Code version and model are pins: checked before the run against `claude
//   --version`, and after it against the stream-json `init` event.
// - The workspace is frozen to EVAL_OUT/workspace for the hidden tests on the scoring computer,
//   with symlinks that leave it dropped.

