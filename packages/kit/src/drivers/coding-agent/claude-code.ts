/** Names in the proxy env file whose values are secrets (redacted everywhere). */
export const PROXY_SECRET_NAMES = ["ANTHROPIC_AUTH_TOKEN", "ANTHROPIC_API_KEY"] as const;

/**
 * Hands the eval user its model credentials and any extra secrets, as 0600 files under
 * \`$eval_home/.anybench-secrets/<NAME>\` (dir 0700), each written through a pipe (never argv).
 * The launcher exports every file to Claude Code and deletes them before it starts.
 *
 * - \`token_source=naive-proxy\`: every \`KEY='value'\` line of the proxy env file (base URL,
 *   the per-trial \`proxy:write\` token, the Naïve model ids, the capability switches). Sets
 *   \`proxy_model\` (ANTHROPIC_MODEL), \`proxy_thinking\` (MAX_THINKING_TOKENS) and
 *   \`proxy_capabilities\` (CLAUDE_CODE_MODEL_CAPABILITIES) for versions.json.
 * - \`token_source=anthropic-key\` (BYOK): ANTHROPIC_API_KEY from the env (the runner exports
 *   ~/.anybench/env to the driver) or the EVAL_SECRETS file.
 * Then each name in \`$secret_names\` the same way as the key. Secret values stay in
 * \`secret_value_<i>\` shell variables for the redactor; sets \`secret_count\`.
 */
export const BASH_SECRETS = `secret_count=0
secret_dir="$eval_home/.anybench-secrets"
as_eval bash -c 'rm -rf "$1" && umask 077 && mkdir -p "$1"' _ "$secret_dir" || fail "cannot create $secret_dir"
put_env() {
  printf '%s' "$2" | as_eval bash -c 'umask 077 && cat > "$1/$2" && chmod 600 "$1/$2"' _ "$secret_dir" "$1" ||
    fail "cannot write $1 for $eval_user"
  if [ "$3" = 1 ]; then
    secret_count=$((secret_count + 1))
    printf -v "secret_value_$secret_count" '%s' "$2"
  fi
}
lookup_secret() {
  local v="\${!1:-}"
  if [ -z "$v" ] && [ -n "\${EVAL_SECRETS:-}" ] && [ -r "$EVAL_SECRETS" ]; then
    v="$(set -a && . "$EVAL_SECRETS" > /dev/null 2>&1 && printf '%s' "\${!1:-}")" || v=""
  fi
  printf '%s' "$v"
}
proxy_model="" proxy_thinking="" proxy_capabilities=""
if [ "$token_source" = naive-proxy ]; then
  proxy_file="\${ANYBENCH_PROXY_ENV_FILE:-$HOME/.anybench/proxy.env}"
  [ -f "$proxy_file" ] && [ -r "$proxy_file" ] ||
    fail "token source naive-proxy: no proxy env file at $proxy_file (the worker writes it with provisionClaudeCodeProxyEnv)"
  saw_url=0 saw_token=0 key_re='^[A-Z_][A-Z0-9_]*$'
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in '' | '#'*) continue ;; esac
    line="\${line#export }"
    k="\${line%%=*}" value="\${line#*=}"
    [[ $k =~ $key_re ]] && [ "$k" != "$line" ] || fail "the proxy env file has a line that is not KEY='value'"
    case "$value" in
      "'"*"'") value="\${value#"'"}" value="\${value%"'"}" ;;
      '"'*'"') value="\${value#'"'}" value="\${value%'"'}" ;;
    esac
    secret=0
    case "$k" in ${PROXY_SECRET_NAMES.join(" | ")}) secret=1 ;; esac
    case "$k" in
      ANTHROPIC_BASE_URL) saw_url=1 ;;
      ANTHROPIC_AUTH_TOKEN) saw_token=1 ;;
      CLAUDE_CODE_MODEL_CAPABILITIES) proxy_capabilities="$value" ;;
    esac
    [ "$secret" = 1 ] || printf -v "proxy_seen_$k" '%s' "$value"
    put_env "$k" "$value" "$secret"
  done < "$proxy_file"
  [ "$saw_url" -eq 1 ] && [ "$saw_token" -eq 1 ] ||
    fail "the proxy env file must set ANTHROPIC_BASE_URL and ANTHROPIC_AUTH_TOKEN"
  # Required proxy switches (TDM-16): added when missing, refused when set to anything else.
${Object.entries(PROXY_REQUIRED_ENV)
  .filter(([k]) => k !== "CLAUDE_CODE_MODEL_CAPABILITIES")
  .map(
    ([
      k,
      v,
    ]) => `  if [ -z "\${proxy_seen_${k}+x}" ]; then put_env ${k} '${v}' 0; proxy_seen_${k}='${v}'; fi
  [ "$proxy_seen_${k}" = '${v}' ] || fail "the proxy env file sets ${k}=$proxy_seen_${k}; the Naïve proxy needs ${k}=${v}"`,
  )
  .join("\n")}
  if [ -z "$proxy_capabilities" ]; then
    proxy_capabilities='${PROXY_REQUIRED_ENV.CLAUDE_CODE_MODEL_CAPABILITIES}'
    put_env CLAUDE_CODE_MODEL_CAPABILITIES "$proxy_capabilities" 0
  fi
  for cap in ${PROXY_DISABLED_CAPABILITIES.map((c) => `-${c}`).join(" ")}; do
    case ",$proxy_capabilities," in *",$cap,"*) ;; *) fail "CLAUDE_CODE_MODEL_CAPABILITIES must include $cap on the Naïve proxy" ;; esac
  done
  proxy_thinking="$proxy_seen_MAX_THINKING_TOKENS"
  # Every model alias resolves to a Naïve id: the main model unless the worker chose another.
  for name in ${PROXY_MODEL_ENV.join(" ")}; do
    seen="proxy_seen_$name"
    if [ -z "\${!seen:-}" ]; then put_env "$name" "$model" 0; printf -v "$seen" '%s' "$model"; fi
    case "\${!seen}" in */*) ;; *) fail "$name=\${!seen} is not a Naïve model id (e.g. anthropic/claude-sonnet-4.6)" ;; esac
  done
  proxy_model="$proxy_seen_ANTHROPIC_MODEL"
else
  value="$(lookup_secret ANTHROPIC_API_KEY)"
  [ -n "$value" ] || fail "secret ANTHROPIC_API_KEY is not set (token source anthropic-key: the worker writes it to ~/.anybench/env)"
  put_env ANTHROPIC_API_KEY "$value" 1
fi
for name in $secret_names; do
  value="$(lookup_secret "$name")"
  [ -n "$value" ] || fail "secret $name is not set (the worker writes it to ~/.anybench/env)"
  put_env "$name" "$value" 1
done
unset value line`;

/**
 * \`redact [<token-cap> <cap-file>]\`: a line filter that replaces every secret value (from
 * BASH_SECRETS) with [REDACTED] and writes each line as soon as it is read, so the runner's
 * token meter still sees the stream live. The values reach it through its environment only.
 *
 * With a token cap it also meters Claude Code's stream-json the way the runner's TokenMeter does
 * (assistant usage once per message id, field-wise max; input + output + cache read + cache
 * creation tokens, subagents included). The line that crosses the cap is still written; then it
 * writes <cap-file> (\`{"token_cap_tokens":N,"tokens":M}\`) and exits 3, which closes the pipe,
 * so Claude Code dies on its next write (EPIPE). The runner's spend cap (token_cap_micro_usd)
 * and wall-clock cap still apply on top.
 */
export const BASH_REDACT = `redact() {
  (
    i=1
    while [ "$i" -le "$secret_count" ]; do
      v="secret_value_$i"
      export "AB_REDACT_$i=\${!v}"
      i=$((i + 1))
    done
    export AB_TOKEN_CAP="\${1:-}" AB_TOKEN_CAP_FILE="\${2:-}"
    exec node -e '
      const fs = require("fs");
      const secrets = Object.keys(process.env)
        .filter((k) => /^AB_REDACT_[0-9]+$/.test(k))
        .map((k) => process.env[k])
        .filter((v) => v.length >= 4);
      for (const k of Object.keys(process.env)) if (k.startsWith("AB_REDACT_")) delete process.env[k];
      const cap = /^[0-9]+$/.test(process.env.AB_TOKEN_CAP || "") ? Number(process.env.AB_TOKEN_CAP) : 0;
      const usage = new Map();
      let anon = 0, stopped = false;
      const n = (v) => (Number.isSafeInteger(v) && v >= 0 ? v : 0);
      const meter = (line) => {
        if (!cap || !line.includes("\\"assistant\\"")) return;
        let e;
        try { e = JSON.parse(line); } catch { return; }
        const m = e && e.type === "assistant" && e.message;
        if (!m || !m.usage) return;
        const u = m.usage;
        const t = [n(u.input_tokens), n(u.output_tokens), n(u.cache_read_input_tokens), n(u.cache_creation_input_tokens)];
        const id = typeof m.id === "string" ? m.id : "anon-" + anon++;
        const prev = usage.get(id);
        usage.set(id, prev ? prev.map((x, i) => Math.max(x, t[i])) : t);
        let total = 0;
        for (const v of usage.values()) total += v[0] + v[1] + v[2] + v[3];
        if (total > cap) {
          stopped = true;
          if (process.env.AB_TOKEN_CAP_FILE)
            fs.writeFileSync(process.env.AB_TOKEN_CAP_FILE, JSON.stringify({ token_cap_tokens: cap, tokens: total }) + "\\n");
        }
      };
      const out = (s) => { try { fs.writeSync(1, s); } catch (err) { if (err.code !== "EAGAIN") throw err; out(s); } };
      let buf = "";
      const emit = (line) => {
        let l = line;
        for (const s of secrets) l = l.split(s).join("[REDACTED]");
        out(l + "\\n");
        meter(line);
        if (stopped) process.exit(3);
      };
      process.stdin.setEncoding("utf8");
      process.stdin.on("data", (chunk) => {
        buf += chunk;
        let i;
        while ((i = buf.indexOf("\\n")) >= 0) { emit(buf.slice(0, i)); buf = buf.slice(i + 1); }
      });
      process.stdin.on("end", () => { if (buf.length) emit(buf); });
    '
  )
}`;

/**
 * The script the eval user runs (\`as_eval bash -c "$claude_launcher" launcher <secret-dir>
 * <task> <ws> <claude args...>\`): load the secret files into the env, delete them, then exec
 * \`claude -p "$(cat task)" <args>\` in the workspace with stdin closed.
 */
export const BASH_CLAUDE_LAUNCHER = `claude_launcher='set -euo pipefail
secret_dir="$1" task="$2" ws="$3"
shift 3
for f in "$secret_dir"/*; do
  [ -f "$f" ] || continue
  n="\${f##*/}"
  v="$(cat "$f")"
  export "$n=$v"
done
rm -rf "$secret_dir"
umask 022
cd "$ws"
prompt="$(cat "$task")"
exec claude -p "$prompt" "$@" < /dev/null'`;

/**
 * \`freeze_workspace <eval-ws> <out-ws> <runner-ws>\`: copy the eval user's workspace to
 * EVAL_OUT/workspace (what the gate tests) and back into EVAL_WS (what \`collect\` globs read),
 * dropping every symlink that resolves outside the workspace. Dropped links are listed in
 * <out>/coding-agent/dropped-links.txt.
 */
export const BASH_FREEZE_WORKSPACE = `freeze_workspace() {
  local from="$1" to="$2" back="$3"
  rm -rf "$to"
  mkdir -p "$to"
  as_eval tar -C "$from" -cf - . | tar -C "$to" --no-same-owner -xf - || return 1
  find "$to" -type l -print0 | node -e '
    const fs = require("fs"), path = require("path");
    const root = path.resolve(process.argv[1]);
    const roots = [root, fs.realpathSync(root)];
    const inside = (p) => roots.some((r) => p === r || p.startsWith(r + path.sep));
    const dropped = [];
    for (const link of fs.readFileSync(0, "utf8").split("\\0").filter(Boolean)) {
      const target = path.resolve(path.dirname(link), fs.readlinkSync(link));
      if (!inside(target)) {
        fs.unlinkSync(link);
        dropped.push(path.relative(root, path.resolve(link)));
      }
    }
    if (dropped.length) fs.writeFileSync(process.argv[2], dropped.join("\\n") + "\\n");
  ' "$to" "$out/coding-agent/dropped-links.txt" || return 1
  find "$back" -mindepth 1 -maxdepth 1 -exec rm -rf {} + || return 1
  tar -C "$to" -cf - . | tar -C "$back" --no-same-owner -xf -
}`;

/**
 * \`stream_init_field <file> <field>\`: \`model\` or \`claude_code_version\` from the first
 * \`system/init\` event of a stream-json file, or nothing.
 */
export const BASH_STREAM_INIT = `stream_init_field() {
  node -e '
    const fs = require("fs");
    for (const line of fs.readFileSync(process.argv[1], "utf8").split("\\n")) {
      if (!line.includes("\\"init\\"")) continue;
      let e;
      try { e = JSON.parse(line); } catch { continue; }
      if (e && e.type === "system" && e.subtype === "init") {
        const v = e[process.argv[2]];
        if (typeof v === "string") process.stdout.write(v);
        break;
      }
    }
  ' "$1" "$2"
}`;

/** \`kill_eval_processes\`: kill whatever the agent left running (only when it is its own uid). */
export const BASH_KILL_EVAL = `kill_eval_processes() {
  [ "$me" != "$eval_user" ] || return 0
  as_eval sh -c 'kill -9 -1' > /dev/null 2>&1 || true
}`;
