/**
 * `fail <message>`: write <out>/coding-agent/error.txt and exit 1. Needs `$out` and `$contender`.
 * `die_usage <message>`: exit 2 before anything was written.
 */
export const BASH_FAIL = `fail() {
  if [ -n "$out" ]; then
    mkdir -p "$out/coding-agent"
    printf '%s\\n' "$*" > "$out/coding-agent/error.txt"
  fi
  echo "driver.sh ($contender): $*" >&2
  exit 1
}
die_usage() { echo "driver.sh ($contender): $*" >&2; exit 2; }`;

/** `is_pinned_version v` / `is_pinned_model m`: the same rules as comparability.ts. */
export const BASH_PIN_PREDICATES = `is_pinned_version() {
  local re='^v?[0-9]+[.][0-9]+[.][0-9]+(-[0-9A-Za-z.-]+)?([+][0-9A-Za-z.-]+)?$' sha='^[0-9a-fA-F]{7,40}$'
  [[ $1 =~ $re ]] || [[ $1 =~ $sha ]]
}
is_pinned_model() {
  local dated='-([0-9]{8}|[0-9]{4}-[0-9]{2}-[0-9]{2})$' latest='(^|[-_.@:])latest$' digit='[0-9]'
  case "$1" in
    '' | sonnet | opus | haiku | opusplan | default | best | auto | latest | main) return 1 ;;
    claude-* | gpt-* | o[0-9]*) [[ $1 =~ $dated ]] ;;
    *) [[ $1 =~ $digit ]] && ! [[ $1 =~ $latest ]] ;;
  esac
}`;

/**
 * Defines \`as_eval <cmd...>\` (run as the eval user, clean env) and sets \`eval_home\`.
 * Needs \`$eval_user\`. With ANYBENCH_EVAL_USER equal to the current user (tests, a VM that runs
 * the driver as eval already), ANYBENCH_EVAL_HOME must name a scratch HOME, so a run can never
 * reset the caller's own ~/.claude.
 */
export const BASH_EVAL_USER = `user_re='^[a-z_][a-z0-9_-]{0,31}$'
[[ $eval_user =~ $user_re ]] || fail "eval user '$eval_user' is not a plain user name"
[ "$eval_user" != root ] || fail "the agent under test never runs as root"
me="$(id -un)"
eval_path="\${ANYBENCH_EVAL_PATH:-$PATH}"
if [ "$me" = "$eval_user" ]; then
  eval_home="\${ANYBENCH_EVAL_HOME:-}"
  [ -n "$eval_home" ] && [ "$eval_home" != "\${HOME:-}" ] ||
    fail "running as $eval_user already: set ANYBENCH_EVAL_HOME to a scratch HOME (never your own)"
  as_eval() { env -i HOME="$eval_home" USER="$eval_user" LOGNAME="$eval_user" PATH="$eval_path" LANG=C.UTF-8 "$@"; }
else
  eval_home="\${ANYBENCH_EVAL_HOME:-$(bash -c "printf %s ~$eval_user")}"
  case "$eval_home" in /*) ;; *) fail "no user '$eval_user' on this computer (the agent-cc profile creates it)" ;; esac
  if [ "$(id -u)" -eq 0 ]; then
    as_eval() { runuser -u "$eval_user" -- env -i HOME="$eval_home" USER="$eval_user" LOGNAME="$eval_user" PATH="$eval_path" LANG=C.UTF-8 "$@"; }
  else
    as_eval() { sudo -n -H -u "$eval_user" -- env -i HOME="$eval_home" USER="$eval_user" LOGNAME="$eval_user" PATH="$eval_path" LANG=C.UTF-8 "$@"; }
  fi
fi
eval_uid="$(as_eval id -u)" || fail "cannot run as $eval_user (runuser, or passwordless sudo to $eval_user, is required)"
[ "$eval_uid" != 0 ] || fail "$eval_user is uid 0: the agent under test never runs as root"`;

