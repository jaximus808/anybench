#!/usr/bin/env bash
# Proof for kits/tandem-vs-claude-code, without Claude Code, Tandem or any network:
#   - applying the oracle (proof/oracle/) passes 100% of the hidden tests for all three tasks,
#   - the untouched starting repo (do-nothing) fails every one of them,
#   - the api-load gate measures p95 only after the hidden tests pass,
#   - bug-hunt's starting repo is exactly its fix commit reverted.
#
#   scripts/verify-proof.sh            run it, print the summary
#   scripts/verify-proof.sh --write    also rewrite PROOF.md with the summary
#
# Runs in Docker (node:22, override with PROOF_IMAGE) with --network none and a random container
# name, so parallel runs never collide. The kit is mounted read-only.
set -euo pipefail
kit="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
image="${PROOF_IMAGE:-node:22}"
write=false
[[ "${1:-}" == "--write" ]] && write=true

out="$(mktemp -d "${TMPDIR:-/tmp}/tvcc-proof.XXXXXX")"
name="tvcc-proof-$(od -An -N6 -tx1 /dev/urandom | tr -d ' \n')"
started="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
host_load="$(uptime | sed -E 's/.*load averages?: *//')"
set +e
docker run --rm --name "$name" --network none \
  -v "$kit:/kit:ro" -v "$out:/out" \
  -e KIT=/kit -e PROOF_OUT=/out \
  "$image" bash /kit/scripts/proof-in-container.sh | tee "$out/console.txt"
status="${PIPESTATUS[0]}"
set -e
image_id="$(docker image inspect "$image" --format '{{.Id}}' 2>/dev/null | cut -c1-19)"

if $write; then
  node_line="$(head -1 "$out/console.txt")"
  {
    cat <<HEAD
# PROOF: tandem-vs-claude-code

Generated by \`kits/tandem-vs-claude-code/scripts/verify-proof.sh --write\` on $started.
Image \`$image\` (\`$image_id\`), \`docker run --network none\`, kit mounted read-only. No Claude Code,
no Tandem, no network: the oracle and do-nothing overlays are the only "contenders".

Environment: $node_line. Host load average when the run started: $host_load (on $(docker info --format '{{.NCPU}}' 2>/dev/null) Docker CPUs).

## What is checked

- **oracle**: \`proof/oracle/driver.sh\` applies the reference solution to a fresh workspace made by the
  workload's \`setup.sh\`; both gates run on it. Every hidden test must pass, and the solution's own tests too.
- **do-nothing**: \`proof/do_less/do-nothing/driver.sh\` leaves the starting repo untouched. Every hidden test
  must fail individually (no crash-hides-tests: tests that never report count as failed), and the
  starting repo's own tests still pass (it is a working repo, just missing the feature or fix).
- **api-load**: measures p95 at 50 req/s on todo-api only after its hidden tests pass. On do-nothing it
  refuses ("no latency without correctness"). The p95 below is from a laptop container and only shows the
  gate works; real numbers come from the eval computers.
- **planted-bug check**: bug-hunt is a planted bug with synthetic history (\`workloads/bug-hunt/PROVENANCE.md\`).
  Its starting repo is byte-for-byte the tree you get by reverting oracle + hidden tests, and that commit
  added exactly the hidden tests.
- **gate convention**: every gate runs as \`check.sh <frozen-out> <workload-id> <gate.json>\` with contender
  code through \`\$AB_RUN\` in \`\$AB_RUN_DIR\` (here \`scripts/ab-run-local.sh\`: clean env, no uid switch),
  as the gate runner (packages/bench gate.ts) calls it on a scoring computer.

## Results

HEAD
    cat "$out/summary.md"
    echo
    echo "Overall: $(tail -1 "$out/console.txt")"
    echo
    echo "Totals: $(node -e '
      const fs = require("fs");
      let o = 0, ot = 0, d = 0, dt = 0;
      for (const w of ["todo-api", "auth-refactor", "bug-hunt"]) {
        const a = JSON.parse(fs.readFileSync(process.argv[1] + "/oracle/" + w + "/hidden-tests/out/hidden-tests.json"));
        const b = JSON.parse(fs.readFileSync(process.argv[1] + "/do-nothing/" + w + "/hidden-tests/out/hidden-tests.json"));
        o += a.passed; ot += a.total; d += b.passed; dt += b.total;
      }
      console.log(`oracle ${o}/${ot} hidden tests passed (100% on 3/3 tasks); do-nothing ${d}/${dt} passed (all ${dt} failed).`);
    ' "$out")"
  } > "$kit/PROOF.md"
  echo "wrote $kit/PROOF.md"
fi
rm -rf "$out"
exit "$status"
