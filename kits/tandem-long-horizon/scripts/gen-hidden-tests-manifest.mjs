#!/usr/bin/env node
// Writes gates/hidden-tests/<workload>/tests.json from the hidden test files (TDM-236 [18.15]).
//
//   node scripts/gen-hidden-tests-manifest.mjs <workload>          # write tests.json
//   node scripts/gen-hidden-tests-manifest.mjs <workload> --check  # exit 1 if tests.json is stale
//
// One file per area: `<area>.test.ts` holds the tests of area <area>, each a top-level
// `test("<name>", ...)` call. `areas` lists, in workloads/<workload>/areas.json order, the areas
// that have a test file, so a half-written workload (TDM-236 before TDM-237) is graded on the
// areas present only. Regenerating is how both halves "merge" tests.json without editing it by hand.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const kit = join(dirname(fileURLToPath(import.meta.url)), "..");

export function buildManifest(workload) {
  const dir = join(kit, "gates/hidden-tests", workload);
  const areasFile = join(kit, "workloads", workload, "areas.json");
  const areaIds = JSON.parse(readFileSync(areasFile, "utf8")).areas.map((a) => a.id);
  const files = readdirSync(dir).filter((f) => f.endsWith(".test.ts"));
  for (const f of files) {
    const area = f.replace(/\.test\.ts$/, "");
    if (!areaIds.includes(area)) throw new Error(`${f}: '${area}' is not an area of ${areasFile}`);
  }
  const areas = areaIds.filter((a) => files.includes(`${a}.test.ts`));
  const tests = [];
  for (const area of areas) {
    const file = `${area}.test.ts`;
    const src = readFileSync(join(dir, file), "utf8");
    for (const m of src.matchAll(/^test\("((?:[^"\\]|\\.)*)"/gm)) tests.push({ file, name: JSON.parse(`"${m[1]}"`), area });
  }
  return {
    workload,
    source: `written for this kit from workloads/${workload}/instruction.md only; generated by scripts/gen-hidden-tests-manifest.mjs, one <area>.test.ts per area of workloads/${workload}/areas.json`,
    areas,
    tests,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const workload = process.argv[2];
  if (!workload) {
    console.error("usage: gen-hidden-tests-manifest.mjs <workload> [--check]");
    process.exit(2);
  }
  const out = join(kit, "gates/hidden-tests", workload, "tests.json");
  const text = `${JSON.stringify(buildManifest(workload), null, 2)}\n`;
  if (process.argv.includes("--check")) {
    const cur = existsSync(out) ? readFileSync(out, "utf8") : "";
    if (cur !== text) {
      console.error(`${out} is stale: run node scripts/gen-hidden-tests-manifest.mjs ${workload}`);
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
    const m = JSON.parse(text);
    console.log(`${out}: ${m.tests.length} tests in ${m.areas.length} areas`);
  }
}
