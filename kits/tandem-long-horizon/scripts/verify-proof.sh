#!/usr/bin/env bash
# Proof for kits/tandem-long-horizon, without Claude Code, Tandem or any network:
#   - applying the oracle (proof/oracle/<workload>/) passes every hidden test (project-tracker
#     120/120, project-tracker-xl 600/600), on ORACLE_REPEATS fresh workspaces (default 3), and its
#     own `npm test` passes,
#   - the untouched starting repo (do-nothing) passes under 1% of them, only the GET /health one,
#   - the oracle without its webhooks area (partial-oracle) fails the gate: a near miss is refused.
#
#   scripts/verify-proof.sh            run it, print the summary
#   scripts/verify-proof.sh --write    also rewrite PROOF.md with the summary
#
# Runs in Docker (node:22, override with PROOF_IMAGE) with --network none and a random container
# name, so parallel runs never collide. The kit is mounted read-only. On any exit (success,
# failure, Ctrl-C) the trap removes this run's container (and only it) and its temp directory.
# PROOF_CPUSET (for example 0-1) pins the container to those CPUs (docker --cpuset-cpus), so the
# test runner sees that many and starts that many test processes; unset, the container gets every
# CPU (the default). PROOF_WORKLOADS narrows the workloads (default: both).
set -euo pipefail
kit="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
image="${PROOF_IMAGE:-node:22}"
repeats="${ORACLE_REPEATS:-3}"
write=false
[[ "${1:-}" == "--write" ]] && write=true

out="$(mktemp -d "${TMPDIR:-/tmp}/tlh-proof.XXXXXX")"
name="tlh-proof-$(od -An -N6 -tx1 /dev/urandom | tr -d ' \n')"
cleanup() {
  docker rm -f "$name" > /dev/null 2>&1 || true
  rm -rf "$out"
}
trap cleanup EXIT
trap 'exit 130' INT TERM

started="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
host_load="$(uptime | sed -E 's/.*load averages?: *//')"
set +e
cpu_args=()
[[ -n "${PROOF_CPUSET:-}" ]] && cpu_args=(--cpuset-cpus "$PROOF_CPUSET")
docker run --rm --name "$name" --network none "${cpu_args[@]}" \
  -v "$kit:/kit:ro" -v "$out:/out" \
  -e KIT=/kit -e PROOF_OUT=/out -e ORACLE_REPEATS="$repeats" \
  -e PROOF_WORKLOADS="${PROOF_WORKLOADS:-project-tracker project-tracker-xl}" \
  "$image" bash /kit/scripts/proof-in-container.sh | tee "$out/console.txt"
status="${PIPESTATUS[0]}"
set -e
image_id="$(docker image inspect "$image" --format '{{.Id}}' 2>/dev/null | cut -c1-19)"

if $write; then
  node_line="$(head -1 "$out/console.txt")"
  {
    cat <<HEAD
# PROOF: tandem-long-horizon

Generated by \`kits/tandem-long-horizon/scripts/verify-proof.sh --write\` on $started.
Image \`$image\` (\`$image_id\`), \`docker run --network none\`, kit mounted read-only. No Claude Code,
no Tandem, no network: the oracle, do-nothing and partial-oracle overlays are the only "contenders".

Environment: $node_line. Host load average when the run started: $host_load (on $(docker info --format '{{.NCPU}}' 2>/dev/null) Docker CPUs${PROOF_CPUSET:+, the container pinned to CPUs $PROOF_CPUSET}).

## What is checked

Two workloads: \`project-tracker\` (v1, 120 hidden tests) and \`project-tracker-xl\` (v2, 600 hidden tests).
For each:

- **oracle**: \`proof/oracle/driver.sh\` applies the reference solution (\`proof/oracle/<workload>/\`,
  zero dependencies, erasable TypeScript, written from \`instruction.md\`) to a fresh workspace made by the
  workload's \`setup.sh\`, then the hidden-tests gate runs on it. Every hidden test must pass (120/120,
  600/600), on each of $repeats fresh workspaces (a flaky test or a timing-dependent oracle would show up as
  a miss), and the solution's own \`npm test\` must pass. Its diff may not touch \`package.json\` (no new
  dependencies) or \`fixtures/tracker-v1.json\`.
- **do-nothing**: \`proof/do_less/do-nothing/driver.sh\` leaves the starting repo untouched. Under 1% of the
  hidden tests may pass, and only \`GET /health\` (the skeleton serves nothing else). Tests that never report
  count as failed. The starting repo's own tests still pass.
- **partial-oracle**: \`proof/do_less/partial-oracle/driver.sh\` applies the workload's oracle, then cuts
  feature area 8 (webhooks) out of it: the 9 routes of \`src/app.ts\` (v1), the 8 routes of
  \`src/r_basics.ts\` (xl). The gate must fail, every webhooks hidden test must fail, and most of the rest
  must still pass (v1: at least 100 of 120; xl: at least 480 of 600, where many tests of other areas
  observe events through a webhook): the gate refuses a whole app with one area missing.
- **gate convention**: the gate runs as \`check.sh <frozen-out> <workload-id> <gate.json>\` with contender
  code through \`\$AB_RUN\` in \`\$AB_RUN_DIR\` (here \`scripts/ab-run-local.sh\`: clean env, no uid switch),
  as the gate runner (packages/bench gate.ts) calls it on a scoring computer.
- **planted regression** (\`proof/regression/skip-tests/\`, a CLAUDE.md that says "skip the tests") needs
  real Claude Code trials, so it is not part of this offline proof.

## Results

HEAD
    cat "$out/summary.md"
    echo
    echo "Overall: $(tail -1 "$out/console.txt")"
    echo
    echo "Totals: $(node -e '
      const fs = require("fs");
      const [dir, nRaw, ...workloads] = process.argv.slice(1);
      const n = Number(nRaw);
      const read = (w, v, i) => JSON.parse(fs.readFileSync(`${dir}/${w}/${v}/${i}/hidden-tests/out/hidden-tests.json`, "utf8"));
      const part = (w, i) => {
        const at = i === 0 ? "" : ` on ${w}`;
        const o = Array.from({ length: n }, (_, k) => read(w, "oracle", k + 1)).map((s) => `${s.passed}/${s.total}`).join(", ");
        const dn = read(w, "do-nothing", 1);
        const po = read(w, "partial-oracle", 1);
        return {
          oracle: i === 0 ? `${o} hidden tests passed (${n} runs)` : `${o}${at} (${n} runs)`,
          dn: i === 0 ? `${dn.passed}/${dn.total} passed` : `${dn.passed}/${dn.total}${at}`,
          po: i === 0 ? `${po.passed}/${po.total} passed, gate failed` : `${po.passed}/${po.total}${at}, gate failed`,
        };
      };
      const parts = workloads.map(part);
      const join = (k) => parts.map((p) => p[k]).join(", ");
      console.log(`oracle ${join("oracle")}; do-nothing ${join("dn")}; partial-oracle ${join("po")}.`);
    ' "$out" "$repeats" ${PROOF_WORKLOADS:-project-tracker project-tracker-xl})"
  } > "$kit/PROOF.md"
  echo "wrote $kit/PROOF.md"
fi
exit "$status"
