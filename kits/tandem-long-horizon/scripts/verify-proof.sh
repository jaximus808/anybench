#!/usr/bin/env bash
# Proof for kits/tandem-long-horizon, without Claude Code, Tandem or any network:
#   - applying the oracle (proof/oracle/project-tracker/) passes 120/120 hidden tests, on
#     ORACLE_REPEATS fresh workspaces (default 3), and its own `npm test` passes,
#   - the untouched starting repo (do-nothing) passes at most 1 hidden test, the GET /health one,
#   - the oracle without its webhooks area (partial-oracle) fails the gate: a near miss is refused.
#
#   scripts/verify-proof.sh            run it, print the summary
#   scripts/verify-proof.sh --write    also rewrite PROOF.md with the summary
#
# Runs in Docker (node:22, override with PROOF_IMAGE) with --network none and a random container
# name, so parallel runs never collide. The kit is mounted read-only. On any exit (success,
# failure, Ctrl-C) the trap removes this run's container (and only it) and its temp directory.
set -euo pipefail
kit="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
image="${PROOF_IMAGE:-node:22}"
repeats="${ORACLE_REPEATS:-3}"
write=false
[[ "${1:-}" == "--write" ]] && write=true

out="$(mktemp -d "${TMPDIR:-/tmp}/tlh-proof.XXXXXX")"
name="tlh-proof-$(od -An -N6 -tx1 /dev/urandom | tr -d ' \n')"
cleanup() {
  docker rm -f "$name" > /dev/null 2>&1 || true
  rm -rf "$out"
}
trap cleanup EXIT
trap 'exit 130' INT TERM

started="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
host_load="$(uptime | sed -E 's/.*load averages?: *//')"
set +e
docker run --rm --name "$name" --network none \
  -v "$kit:/kit:ro" -v "$out:/out" \
  -e KIT=/kit -e PROOF_OUT=/out -e ORACLE_REPEATS="$repeats" \
  "$image" bash /kit/scripts/proof-in-container.sh | tee "$out/console.txt"
status="${PIPESTATUS[0]}"
set -e
image_id="$(docker image inspect "$image" --format '{{.Id}}' 2>/dev/null | cut -c1-19)"

if $write; then
  node_line="$(head -1 "$out/console.txt")"
  {
    cat <<HEAD
# PROOF: tandem-long-horizon

Generated by \`kits/tandem-long-horizon/scripts/verify-proof.sh --write\` on $started.
Image \`$image\` (\`$image_id\`), \`docker run --network none\`, kit mounted read-only. No Claude Code,
no Tandem, no network: the oracle, do-nothing and partial-oracle overlays are the only "contenders".

Environment: $node_line. Host load average when the run started: $host_load (on $(docker info --format '{{.NCPU}}' 2>/dev/null) Docker CPUs).

## What is checked

- **oracle**: \`proof/oracle/driver.sh\` applies the reference solution (\`proof/oracle/project-tracker/\`,
  zero dependencies, erasable TypeScript, written from \`instruction.md\`) to a fresh workspace made by the
  workload's \`setup.sh\`, then the hidden-tests gate runs on it. Every one of the 120 hidden tests must pass,
  on each of $repeats fresh workspaces (a flaky test or a timing-dependent oracle would show up as a miss),
  and the solution's own \`npm test\` must pass. Its diff may not touch \`package.json\` (no new dependencies)
  or \`fixtures/tracker-v1.json\`.
- **do-nothing**: \`proof/do_less/do-nothing/driver.sh\` leaves the starting repo untouched. At most 1 hidden
  test may pass, and only \`GET /health\` (the skeleton serves nothing else). Tests that never report
  count as failed. The starting repo's own tests still pass.
- **partial-oracle**: \`proof/do_less/partial-oracle/driver.sh\` applies the oracle, then cuts feature area 8
  (webhooks, its 9 routes) out of \`src/app.ts\`. The gate must fail, every webhooks hidden test must fail,
  and at least 100 of the 120 must still pass: the gate refuses a whole app with one area missing.
- **gate convention**: the gate runs as \`check.sh <frozen-out> <workload-id> <gate.json>\` with contender
  code through \`\$AB_RUN\` in \`\$AB_RUN_DIR\` (here \`scripts/ab-run-local.sh\`: clean env, no uid switch),
  as the gate runner (packages/bench gate.ts) calls it on a scoring computer.
- **planted regression** (\`proof/regression/skip-tests/\`, a CLAUDE.md that says "skip the tests") needs
  real Claude Code trials, so it is not part of this offline proof.

## Results

HEAD
    cat "$out/summary.md"
    echo
    echo "Overall: $(tail -1 "$out/console.txt")"
    echo
    echo "Totals: $(node -e '
      const fs = require("fs");
      const dir = process.argv[1], n = Number(process.argv[2]);
      const read = (v, i) => JSON.parse(fs.readFileSync(`${dir}/${v}/${i}/hidden-tests/out/hidden-tests.json`, "utf8"));
      const oracle = Array.from({ length: n }, (_, i) => read("oracle", i + 1));
      const dn = read("do-nothing", 1);
      const po = read("partial-oracle", 1);
      const o = oracle.map((s) => `${s.passed}/${s.total}`).join(", ");
      console.log(`oracle ${o} hidden tests passed (${n} runs); do-nothing ${dn.passed}/${dn.total} passed; partial-oracle ${po.passed}/${po.total} passed, gate failed.`);
    ' "$out" "$repeats")"
  } > "$kit/PROOF.md"
  echo "wrote $kit/PROOF.md"
fi
exit "$status"
